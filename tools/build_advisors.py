"""France's military advisors: python tools/build_advisors.py

Vanilla locks Gamelin, Weygand and de Gaulle behind vanilla focuses this mod does not have. This copies
common/characters/FRA.txt and, inside military advisor slots only, replaces every vanilla focus requirement with the
"참모본부 개편" focus (LR_FRA_general_staff), so the tooltip names the focus. Political advisors keep their vanilla conditions.
"""
import re
from pathlib import Path

import build_world as world

SOURCE = world.VANILLA / "common" / "characters" / "FRA.txt"
TARGET = world.MOD / "common" / "characters" / "FRA.txt"
NOTE = "# Generated by tools/build_advisors.py from vanilla FRA.txt: military advisors open with the 참모본부 개편 focus.\n"
MILITARY = {"army_chief", "navy_chief", "air_chief", "high_command", "theorist"}
FLAG = "has_completed_focus = LR_FRA_general_staff"  # shown in game by the focus name, "참모본부 개편"


def block_end(text, start):
    """Index just past the brace that closes the block opened at text[start] == '{'."""
    depth = 0
    for i in range(start, len(text)):
        depth += (text[i] == "{") - (text[i] == "}")
        if depth == 0:
            return i + 1
    raise SystemExit("unbalanced braces in vanilla FRA.txt")


def main():
    text = SOURCE.read_text(encoding="utf-8-sig")
    out, pos, opened = [], 0, []
    for m in re.finditer(r"advisor\s*=\s*\{", text):
        if m.start() < pos:
            continue
        end = block_end(text, m.end() - 1)
        block = text[m.start():end]
        slot = re.search(r"slot\s*=\s*(\w+)", block)
        if slot and slot.group(1) in MILITARY and "has_completed_focus" in block:
            block = re.sub(r"has_completed_focus\s*=\s*FRA_\w+", FLAG, block)
            opened.append(re.search(r"idea_token\s*=\s*(\w+)", block).group(1))
        out.append(text[pos:m.start()] + block)
        pos = end
    out.append(text[pos:])
    TARGET.write_text(NOTE + "".join(out), encoding="utf-8")
    print(f"OK: {len(opened)} military advisor slots open with the general staff focus: {', '.join(opened)}")


if __name__ == "__main__":
    main()
