"""AI for France when nobody plays it: python tools/build_ai.py

Vanilla's France strategy (common/ai_strategy/FRA.txt) and its two strategy plans were written for 1939: they ally
with Britain, guard Belgium and hate Germany only. Files of the same names here replace them.

What an AI France does in this world:
  - builds an army for a land war in Europe (infantry and artillery, some armour), a modest air force and a fleet of
    submarines and screens for the Channel;
  - prepares for the wars of its route one at a time, in the order the focus trees declare them: the Rhine (North
    Germany), the Danube (Austria), the Channel (Britain), Russia. The next target is only prepared once the one before
    it is gone or France's subject;
  - in a war, wants to conquer the enemy, and against Britain plans landings.
The focus tree's own weights (build_france.ai_will_do) make it take industry first and a war focus once it opens.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "mod"
NOTE = "# Generated by tools/build_ai.py.\n"
WARS = ["GER", "AUS", "ENG", "SOV"]  # the order the routes' focuses declare them

PRODUCTION = """LR_FRA_ai_army = {
	allowed = { original_tag = FRA }
	enable = { always = yes }
	abort = { always = no }
	ai_strategy = { type = role_ratio id = infantry value = 65 }
	ai_strategy = { type = role_ratio id = armor value = 15 }
	ai_strategy = { type = role_ratio id = mountaineers value = 10 }
	ai_strategy = { type = role_ratio id = garrison value = 5 }
	ai_strategy = { type = role_ratio id = marines value = 5 }
	ai_strategy = { type = role_ratio id = paratroopers value = 0 }
	ai_strategy = { type = role_ratio id = cavalry value = 0 }
	ai_strategy = { type = unit_ratio id = fighter value = 60 }
	ai_strategy = { type = unit_ratio id = cas value = 20 }
	ai_strategy = { type = unit_ratio id = tactical_bomber value = 10 }
	ai_strategy = { type = unit_ratio id = naval_bomber value = 5 }
	ai_strategy = { type = unit_ratio id = strategic_bomber value = 0 }
	ai_strategy = { type = unit_ratio id = capital_ship value = 15 }
	ai_strategy = { type = unit_ratio id = submarine value = 40 }
	ai_strategy = { type = unit_ratio id = screen_ship value = 30 }
	ai_strategy = { type = unit_ratio id = convoy value = 15 }
	ai_strategy = { type = equipment_production_factor id = infantry value = 35 }
	ai_strategy = { type = equipment_production_factor id = artillery value = 25 }
	ai_strategy = { type = equipment_production_factor id = armor value = 20 }
	ai_strategy = { type = equipment_production_factor id = fighter value = 20 }
}

LR_FRA_ai_europe_first = {
	allowed = { original_tag = FRA }
	enable = { always = yes }
	abort = { always = no }
	ai_strategy = { type = area_priority id = europe value = 150 }
	ai_strategy = { type = area_priority id = north_africa value = 40 }
	ai_strategy = { type = area_priority id = scandinavia value = 0 }
	ai_strategy = { type = area_priority id = north_america value = 0 }
	ai_strategy = { type = area_priority id = south_america value = 0 }
	ai_strategy = { type = area_priority id = asia value = 0 }
	ai_strategy = { type = area_priority id = pacific value = 0 }
}

LR_FRA_ai_rearm_in_peace = {
	allowed = { original_tag = FRA }
	enable = { has_war = no }
	abort_when_not_enabled = yes
	ai_strategy = { type = added_military_to_civilian_factory_ratio value = 30 }
}
"""


def gone(tag):
    """True once a war target no longer stands in the way: destroyed or France's subject."""
    return f"OR = {{ NOT = {{ country_exists = {tag} }} {tag} = {{ is_subject_of = FRA }} }}"


def war_strategies():
    blocks = []
    for i, tag in enumerate(WARS):
        before = "".join(f"\n\t\t{gone(t)}" for t in WARS[:i])
        blocks.append(f"""LR_FRA_ai_prepare_{tag} = {{
	allowed = {{ original_tag = FRA }}
	enable = {{
		country_exists = {tag}
		NOT = {{ {tag} = {{ is_subject_of = FRA }} }}
		NOT = {{ has_war_with = {tag} }}{before}
	}}
	abort_when_not_enabled = yes
	ai_strategy = {{ type = antagonize id = {tag} value = 100 }}
	ai_strategy = {{ type = prepare_for_war id = {tag} value = 100 }}
	ai_strategy = {{ type = contain id = {tag} value = 50 }}
}}

LR_FRA_ai_war_{tag} = {{
	allowed = {{ original_tag = FRA }}
	enable = {{ has_war_with = {tag} }}
	abort_when_not_enabled = yes
	ai_strategy = {{ type = conquer id = {tag} value = 200 }}
	ai_strategy = {{ type = antagonize id = {tag} value = 200 }}
	ai_strategy = {{ type = front_unit_request tag = {tag} value = 50 }}
}}
""")
    blocks.append("""LR_FRA_ai_cross_the_channel = {
	allowed = { original_tag = FRA }
	enable = { has_war_with = ENG }
	abort_when_not_enabled = yes
	ai_strategy = { type = invade id = ENG value = 200 }
}
""")
    return "\n".join(blocks)


def main():
    folder = MOD / "common" / "ai_strategy"
    folder.mkdir(parents=True, exist_ok=True)
    # Same file name as vanilla's: it replaces the 1939 strategy entirely.
    (folder / "FRA.txt").write_text(NOTE + PRODUCTION + "\n" + war_strategies(), encoding="utf-8")
    plans = MOD / "common" / "ai_strategy_plans"
    plans.mkdir(parents=True, exist_ok=True)
    for name in ("FRA_historical_strategy_plan.txt", "FRA_alternate_strategy_plan.txt"):
        (plans / name).write_text(NOTE + "# Emptied: vanilla's plan names focuses this France does not have.\n", encoding="utf-8")
    print(f"OK: France AI written ({len(WARS)} wars in order)")


if __name__ == "__main__":
    main()
