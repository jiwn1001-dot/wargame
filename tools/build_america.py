def link_focuses():
    """Focuses move their route's index (GAINS) and later ones need it (NEEDS)."""
    by_id = {item["id"]: item for tree in F.TREES.values() for item in tree["focuses"]}
    for fid, (key, n) in M.GAINS.items():
        by_id[fid]["effects"] = tuple(by_id[fid]["effects"]) + (M.gain(key, n),)
    for fid, (key, n) in M.NEEDS.items():
        item = by_id[fid]
        item["available"] = "\n".join(x for x in (item["available"], M.need(key, n)) if x)
    missing = (set(M.GAINS) | set(M.NEEDS)) - set(by_id)
    if missing:
        raise SystemExit(f"minigame links to unknown focuses: {sorted(missing)}")


def minigame_effects():
    out = []
    for key, m in M.MINIGAMES.items():
        var = m["var"]
        update = [f"clamp_variable = {{\n\tvar = {var}\n\tmin = 0\n\tmax = 100\n}}"]
        for i, scale in enumerate(m["mods"].values()):
            update.append(f"set_variable = {{ {var}_m{i} = {var} }}\nsubtract_from_variable = {{ {var}_m{i} = 50 }}\n"
                          f"multiply_variable = {{ {var}_m{i} = {scale} }}")
        out.append(f"lr_usa_mg_{key}_update = {{\n" + indent("\n".join(update)) + "\n}")
        out.append(f"lr_usa_mg_{key}_start = {{\n\tif = {{\n\t\tlimit = {{ NOT = {{ has_country_flag = LR_usa_mg_{key} }} }}\n"
                   f"\t\tset_country_flag = LR_usa_mg_{key}\n\t\tset_variable = {{ {var} = {m['start']} }}\n"
                   f"\t\tadd_dynamic_modifier = {{ modifier = LR_usa_mg_{key} }}\n\t\tlr_usa_mg_{key}_update = yes\n\t}}\n}}")
        out.append(f"lr_usa_mg_{key}_stop = {{\n\tif = {{\n\t\tlimit = {{ has_country_flag = LR_usa_mg_{key} }}\n"
                   f"\t\tclr_country_flag = LR_usa_mg_{key}\n\t\tremove_dynamic_modifier = {{ modifier = LR_usa_mg_{key} }}\n\t}}\n}}")
    monthly = [f"if = {{\n\tlimit = {{ has_country_flag = LR_usa_mg_{key} }}\n\tsubtract_from_variable = {{ {m['var']} = {m['decay']} }}\n"
               f"\tlr_usa_mg_{key}_update = yes\n}}" for key, m in M.MINIGAMES.items()]
