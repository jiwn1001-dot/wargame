def check():
    gfx = (VANILLA / "interface" / "goals.gfx").read_text(encoding="utf-8-sig", errors="ignore")
    tags = "\n".join(p.read_text(encoding="utf-8-sig", errors="ignore") for p in (VANILLA / "common" / "technology_tags").glob("*.txt"))
    pictures = "\n".join(p.read_text(encoding="utf-8-sig", errors="ignore") for p in (VANILLA / "interface").glob("*.gfx"))
    ids = set()
    problems = []
    for tree in F.TREES.values():
        for item in tree["focuses"]:
            if item["id"] in ids:
                problems.append(f"duplicate focus {item['id']}")
            ids.add(item["id"])
            if f'"GFX_goal_generic_{item["icon"]}"' not in gfx:
                problems.append(f"{item['id']}: unknown icon {item['icon']}")
            for effect in item["effects"]:
                for category in re.findall(r"category = (\w+)", effect):
                    if not re.search(rf"^\s*{category}\s*$", tags, re.M):
                        problems.append(f"{item['id']}: unknown technology category {category}")
    for tree in F.TREES.values():
        positions = {}
        for item in tree["focuses"]:
            for group in list(item["pre"]) + [tuple(item["me"])]:
                for option in (group if isinstance(group, tuple) else (group,)):
                    if option not in ids:
                        problems.append(f"{item['id']}: unknown focus {option}")
            spot = (item["x"], item["y"])
            if spot in positions:
                problems.append(f"{item['id']} and {positions[spot]} share a spot")
            positions[spot] = item["id"]
    everything = "\n".join("\n".join(i["effects"]) for t in F.TREES.values() for i in t["focuses"])
    everything += "\n".join((e["immediate"] or "") + "".join(o[1] for o in e["options"]) for e in E.EVENTS.values())
    everything += "\n" + civil_war_effect() + capitulation_effect() + startup_effect()
    for n in sorted(set(int(x) for x in re.findall(r"lr_usa\.(\d+)", everything))):
        if n not in E.EVENTS:
            problems.append(f"lr_usa.{n} is used but not written")
    for name in set(re.findall(r"\b(LR_usa_[a-z_]+)\b", everything)):
        if (re.search(rf"(add_ideas|remove_ideas|idea|add_idea|remove_idea|has_idea) = {name}\b", everything)
                and name not in E.IDEAS):
            problems.append(f"unknown spirit {name}")
    for e in E.EVENTS.values():
        if e["picture"] and f'"{e["picture"]}"' not in pictures:
            problems.append(f"unknown event picture {e['picture']}")
    for key in set(re.findall(r"custom_effect_tooltip = (\w+)", everything)) | set(re.findall(r"tooltip = (LR_tt_usa_\w+)", everything)):
        if key.startswith("LR_tt_usa") and key not in E.LOC and key not in M.TOOLTIPS and key not in R.loc():
            problems.append(f"no text for {key}")
    if problems:
        raise SystemExit("\n".join(problems))


