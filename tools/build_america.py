def esc(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n\n", "\\n\\n").replace("\n", " ")


def loc_line(key, text):
    # Event text keeps \n\n as written; esc() would double the backslash, so do it by hand here.
    return f' {key}:0 "{esc(text)}"'


