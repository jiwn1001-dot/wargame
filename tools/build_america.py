LETTERS = "abcdefgh"


def render_event(n, e):
    kind = "news_event" if e["news"] else "country_event"
    key = f"lr_usa.{n}"
    lines = [f"{kind} = {{", f"\tid = {key}"]
    if e["hidden"]:
        lines.append("\thidden = yes")
    else:
        lines += [f"\ttitle = {key}.t", f"\tdesc = {key}.d", f"\tpicture = {e['picture']}"]
        if e["news"]:
            lines.append("\tmajor = yes")
    lines.append("\tis_triggered_only = yes")
    if e["trigger"]:
        lines += ["\ttrigger = {", indent(e["trigger"], 2), "\t}"]
    if e["immediate"]:
        lines += ["\timmediate = {", indent(e["immediate"].strip(), 2), "\t}"]
    for i, (_, effects, ai, trigger) in enumerate(e["options"]):
        lines += ["\toption = {", f"\t\tname = {key}.{LETTERS[i]}"]
        if trigger:
            lines += ["\t\ttrigger = {", indent(trigger, 3), "\t\t}"]
        if ai is not None:
            lines.append(f"\t\tai_chance = {{ factor = {ai} }}" if isinstance(ai, int) else "\t\tai_chance = {\n" + indent(ai, 3) + "\n\t\t}")
        if effects:
            lines.append(indent(effects.strip(), 2))
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines)


