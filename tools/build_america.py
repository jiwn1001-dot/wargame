def ai_will_do(item):
    text = "\n".join(item["effects"])
    factor = item["ai"]
    lines = ["\t\tai_will_do = {", f"\t\t\tfactor = {factor}"]
    if "declare_war_on" in text:
        lines.append("\t\t\tmodifier = { factor = 0.1 has_war = yes }")
    elif any(k in text for k in ("arms_factory", "industrial_complex", "dockyard", "add_research_slot")):
        lines[1] = f"\t\t\tfactor = {factor * 2}"
    lines.append("\t\t}")
    return "\n".join(lines)


def render_focus(item):
    lines = ["\tfocus = {", f"\t\tid = {item['id']}", f"\t\ticon = GFX_goal_generic_{item['icon']}", f"\t\tx = {item['x']}", f"\t\ty = {item['y']}"]
    for group in item["pre"]:
        options = group if isinstance(group, tuple) else (group,)
        lines.append("\t\tprerequisite = { " + " ".join(f"focus = {o}" for o in options) + " }")
    if item["me"]:
        lines.append("\t\tmutually_exclusive = { " + " ".join(f"focus = {o}" for o in item["me"]) + " }")
    conditions = []
    if item["branch"]:
        lines.append(f"\t\tallow_branch = {{ has_country_flag = {item['branch']} }}")
        conditions.append(f"has_country_flag = {item['branch']}")
    if item["available"]:
        conditions.append(item["available"])
    if conditions:
        lines.extend(["\t\tavailable = {", indent("\n".join(conditions), 3), "\t\t}"])
    lines.extend([f"\t\tcost = {item['cost']}", ai_will_do(item), "\t\tcompletion_reward = {"])
    lines.extend(indent(effect, 3) for effect in item["effects"])
    lines.extend(["\t\t}", "\t}"])
    return "\n".join(lines)


def render_tree(tree_id, tree):
    root = tree["focuses"][0]["id"]
    tags = "\n".join(f"\t\tmodifier = {{\n\t\t\tadd = 10\n\t\t\ttag = {t}\n\t\t}}" for t in tree["tags"])
    head = (f"focus_tree = {{\n\tid = {tree_id}\n\n\tcountry = {{\n\t\tfactor = 0\n{tags}\n\t}}\n\n\tdefault = no\n"
            f"\tcontinuous_focus_position = {{ x = 50 y = 1400 }}\n\tinitial_show_position = {{\n\t\tfocus = {root}\n\t}}\n\n")
    return head + "\n\n".join(render_focus(item) for item in tree["focuses"]) + "\n}\n"


