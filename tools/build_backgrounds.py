"""Loading screens and the main menu background from docs/art/background.png: python tools/build_backgrounds.py

The game's screens are 1920x1440 (4:3) and are cropped top and bottom on a 16:9 monitor. The picture (16:9) goes in
the middle band at full width; above and below it a blurred, darkened copy fills the rest, so nothing of the picture
is lost on either kind of screen. Every vanilla and DLC loading screen is replaced, and the background database
lists only this picture, so the menu always shows it.
"""
from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter

PROJECT = Path(__file__).resolve().parent.parent
MOD = PROJECT / "mod"
SOURCE = PROJECT / "docs" / "art" / "background.png"
# The main menu logo, in place of HEARTS OF IRON (vanilla gfx/interface/logo_game.dds is 448x175, shown at the top left).
LOGO = PROJECT / "docs" / "art" / "logo.png"
LOGO_WIDTH = 520
# The song for the menu and the loading screens.
ANTHEM = PROJECT / "docs" / "art" / "marseillaise_source.mp3"
SIZE, SMALL = (1920, 1440), (192, 144)
NAMES = [f"load_{n}" for n in range(1, 10)] + [
    "load_aat", "load_aat2", "load_bba", "load_botb", "load_goe", "load_lar", "load_ncns_chi", "load_ncns_jap",
    "load_nsb", "load_nsb2", "load_taog_ast", "load_toa", "load_ww", "load_lr"]


def compose(picture):
    width, height = SIZE
    scale = max(width / picture.width, height / picture.height)
    fill = picture.resize((round(picture.width * scale), round(picture.height * scale)), Image.LANCZOS)
    left, top = (fill.width - width) // 2, (fill.height - height) // 2
    fill = fill.crop((left, top, left + width, top + height)).filter(ImageFilter.GaussianBlur(28))
    fill = ImageEnhance.Brightness(fill).enhance(0.45)
    band = picture.resize((width, round(picture.height * width / picture.width)), Image.LANCZOS)
    fill.paste(band, (0, (height - band.height) // 2))
    return fill


def main():
    picture = Image.open(SOURCE).convert("RGB")
    screen = compose(picture)
    small = screen.resize(SMALL, Image.LANCZOS)
    folder = MOD / "gfx" / "loadingscreens"
    folder.mkdir(parents=True, exist_ok=True)
    for name in NAMES:
        screen.save(folder / f"{name}.dds", "DDS", pixel_format="DXT1")
        small.save(folder / f"{name}_small.dds", "DDS", pixel_format="DXT1")
    backgrounds = MOD / "common" / "frontend" / "backgrounds"
    backgrounds.mkdir(parents=True, exist_ok=True)
    (backgrounds / "base_backgrounds.txt").write_text(
        "# Generated by tools/build_backgrounds.py: the mod's only menu background.\nload_lr = {\n}\n", encoding="utf-8")
    (MOD / "interface" / "lr_backgrounds.gfx").write_text(
        'spriteTypes = {\n\tspriteType = {\n\t\tname = "GFX_load_lr_small"\n\t\ttexturefile = "gfx/loadingscreens/load_lr_small.dds"\n\t}\n}\n',
        encoding="utf-8")
    logo = Image.open(LOGO).convert("RGBA")
    logo = logo.crop(logo.getbbox())  # trim the transparent margin
    logo = logo.resize((LOGO_WIDTH, round(logo.height * LOGO_WIDTH / logo.width)), Image.LANCZOS)
    logo.save(MOD / "gfx" / "interface" / "logo_game.dds", "DDS")
    print(f"OK: {len(NAMES)} loading screens, the menu background and the {logo.width}x{logo.height} logo")
    # La Marseillaise in place of the main theme: the menu and the loading screens play the song named "maintheme",
    # whose file is hoi4mainthemeallies.ogg, so a file of that name in the mod replaces it. Loudness is evened out.
    import subprocess

    import imageio_ffmpeg
    target = MOD / "music" / "hoi4mainthemeallies.ogg"
    target.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-y", "-v", "error", "-i", str(ANTHEM), "-af", "loudnorm=I=-16:TP=-1.5",
                    "-ar", "44100", "-c:a", "libvorbis", "-q:a", "5", str(target)], check=True)
    print(f"OK: La Marseillaise as the main theme ({target.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
