"""The election campaign map for the parliamentary republic.

A map of metropolitan France by state, its regions tinted by how they lean, and a pin on each region: click a pin
to hold a rally there. A list beside the map shows each region's support and buys newspaper campaigns. Every month
brings four campaign actions; support drifts back with regional discontent. At each election the government's
seats are counted region by region: seats x support, after stability, war and chance have had their say.

Writes the map art, the GUI, the scripted GUI, the decision category, the effects and their text.
build_systems.py calls main(); victory.py's election event calls lr_fra_election_count.
"""
