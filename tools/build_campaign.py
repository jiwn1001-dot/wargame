MOD, VANILLA = world.MOD, world.VANILLA
NOTE = "# Generated by tools/build_campaign.py.\n"
SEAT_ROUTES = ("LR_route_jacobin", "LR_route_girondin", "LR_route_marais", "LR_route_guardian")
# key, name, states, seats (610 in all), baseline support for the government
REGIONS = [
    ("paris", "파리", [16, 24, 18], 120, 52),
    ("nord", "북부", [29, 785, 15, 27], 100, 50),
    ("vendee", "방데·브르타뉴", [14, 30, 23, 19], 90, 44),
    ("midi", "남부", [22, 31, 806, 25, 33], 110, 50),
    ("rhone", "론·프로방스", [21, 851, 32, 26, 20, 1], 100, 50),
    ("lorraine", "로렌·알자스", [17, 28], 50, 48),
    ("africa", "튀니지·모로코", [458, 461, 462, 665], 40, 46),
]
MAP_W = 260  # the decision panel is about 500 pixels wide: map and list must fit side by side
FRAMES = 5  # strong opposition, leaning opposition, toss-up, leaning government, strong government
TINTS = [(150, 40, 40), (200, 110, 90), (150, 140, 120), (90, 130, 190), (40, 80, 170)]
RALLY_PP, RALLY_GAIN, PRESS_FUNDS, PRESS_GAIN, ACTIONS = 15, 4, 10, 6, 4


def province_arrays():
    states = rm.state_data()
    image = Image.open(VANILLA / "map" / "provinces.bmp").convert("RGB")
    defs = {}
    for line in (VANILLA / "map" / "definition.csv").read_text(encoding="utf-8", errors="ignore").splitlines():
        parts = line.split(";")
        if len(parts) > 4 and parts[0].isdigit():
            defs[int(parts[1]) * 65536 + int(parts[2]) * 256 + int(parts[3])] = int(parts[0])
    return states, image, defs


def build_map():
    states, image, defs = province_arrays()
    metro = [r for r in REGIONS if r[0] != "africa"]
    state_region = {s: key for key, _, ss, *_ in metro for s in ss}
    prov_state = {p: s for s, (_, ps) in states.items() for p in ps if s in state_region}
    # The bounding box of metropolitan France in the province bitmap.
    full = np.array(image)
    key = full[:, :, 0].astype(np.int64) * 65536 + full[:, :, 1].astype(np.int64) * 256 + full[:, :, 2]
    uniq, inv = np.unique(key, return_inverse=True)
    state_of = np.array([prov_state.get(defs.get(int(k), -1), -1) for k in uniq])[inv].reshape(key.shape)
    ys, xs = np.nonzero(state_of > 0)
    pad = 6
    top, bottom, left, right = ys.min() - pad, ys.max() + pad, xs.min() - pad, xs.max() + pad
    crop = state_of[top:bottom, left:right]
    scale = MAP_W / crop.shape[1]
    height = round(crop.shape[0] * scale)
    rows = (np.arange(height) * crop.shape[0] / height).astype(int)
    cols = (np.arange(MAP_W) * crop.shape[1] / MAP_W).astype(int)
    grid = crop[rows][:, cols]
    region_grid = np.full(grid.shape, "", dtype=object)
    for s, r in state_region.items():
        region_grid[grid == s] = r
    # Base map: dark sea, parchment land, thin state borders, gold region borders.
    base = np.zeros((height, MAP_W, 4), dtype=np.uint8)
    base[...] = (18, 22, 30, 255)
    land = grid > 0
    base[land] = (210, 196, 160, 255)
    state_edge = np.zeros(grid.shape, bool)
    state_edge[1:, :] |= grid[1:, :] != grid[:-1, :]
    state_edge[:, 1:] |= grid[:, 1:] != grid[:, :-1]
    region_edge = np.zeros(grid.shape, bool)
    region_edge[1:, :] |= region_grid[1:, :] != region_grid[:-1, :]
    region_edge[:, 1:] |= region_grid[:, 1:] != region_grid[:, :-1]
    base[state_edge & land] = (120, 104, 76, 255)
    base[region_edge] = (214, 178, 96, 255)
    folder = MOD / "gfx" / "interface" / "lr"
    folder.mkdir(parents=True, exist_ok=True)
    framed = Image.fromarray(base, "RGBA")
    ImageDraw.Draw(framed).rectangle((0, 0, MAP_W - 1, height - 1), outline=(214, 178, 96, 255), width=2)
    framed.save(folder / "lr_campaign_map.dds", pixel_format="DXT5")
    # One overlay per region: five frames side by side, its shape tinted by how it leans.
    centres = {}
    for key, *_ in metro:
        mask = region_grid == key
        my, mx = np.nonzero(mask)
        centres[key] = (int(mx.mean()), int(my.mean()))
        strip = np.zeros((height, MAP_W * FRAMES, 4), dtype=np.uint8)
        for f, tint in enumerate(TINTS):
            strip[:, f * MAP_W:(f + 1) * MAP_W][mask & ~region_edge] = tint + (165,)
        Image.fromarray(strip, "RGBA").save(folder / f"lr_campaign_{key}.dds", pixel_format="DXT5")
    # The pin.
    pin = Image.new("RGBA", (22, 22), (0, 0, 0, 0))
    d = ImageDraw.Draw(pin)
    d.ellipse((2, 2, 19, 19), fill=(24, 20, 18, 255), outline=(214, 178, 96, 255), width=2)
    d.ellipse((8, 8, 13, 13), fill=(236, 204, 128, 255))
    pin.save(folder / "lr_campaign_pin.dds", pixel_format="DXT5")
    return height, centres


def gui(height, centres):
    sprites = ['spriteTypes = {',
               '\tspriteType = {\n\t\tname = "GFX_lr_campaign_map"\n\t\ttexturefile = "gfx/interface/lr/lr_campaign_map.dds"\n\t}',
               '\tspriteType = {\n\t\tname = "GFX_lr_campaign_pin"\n\t\ttexturefile = "gfx/interface/lr/lr_campaign_pin.dds"\n\t}']
    for key in centres:
        sprites.append(f'\tspriteType = {{\n\t\tname = "GFX_lr_campaign_{key}"\n\t\ttexturefile = "gfx/interface/lr/lr_campaign_{key}.dds"\n\t\tnoOfFrames = {FRAMES}\n\t}}')
    sprites.append("}")
    (MOD / "interface" / "lr_campaign.gfx").write_text("\n".join(sprites) + "\n", encoding="utf-8")

    rows = len(REGIONS)
    win_h = max(height + 50, 50 + 34 * rows) + 34
