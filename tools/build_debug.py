"""Debug decisions: open any French route's focus tree at once. Visible only when the game runs with -debug.

Each decision clears every route flag, sets the chosen one and applies what the route's entry event would:
regime and ruler spirits, government, leader and name. Napoleon's three roads also need his trunk, so their
decisions complete the fork focus itself, whose own effects finish the entry.
build_france.py calls main() after writing the focus tree.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD = world.MOD
NOTE = "# Generated by tools/build_debug.py.\n"
ALL_ROUTES = ["orleans", "bourbon", "communist", "anarchist", "jacobin", "girondin", "marais", "napoleon", "empire", "guardian", "red", "petain", "vanquished"]
# route: name, regime, ruler (None: no ruler), government, leader effect, cosmetic tag, fork focus to complete.
ROUTES = {
    "orleans": ("오를레앙 왕정", "orleans", "orleans", "fascism", "promote_character = LR_FRA_orleans", None, None),
    "bourbon": ("부르봉 왕정", "bourbon", "louis", "neutrality", "promote_character = FRA_louis_xx", None, None),
    "communist": ("코뮌", "communist", None, "communism", None, None, None),
    "anarchist": ("자유 코뮌 연합", "anarchist", None, "communism", "promote_character = LR_FRA_besnard", "LR_FRA_federation", None),
    "jacobin": ("산악파", "jacobin", None, "democratic", "promote_character = LR_FRA_blum", None, None),
    "girondin": ("지롱드", "girondin", None, "democratic", None, None, None),
    "marais": ("푀양파", "marais", None, "democratic", None, None, None),
    "napoleon": ("나폴레옹 통령정", "napoleon", None, "democratic",
                 "promote_character = {\n\tcharacter = FRA_napoleon_bonaparte\n\tideology = conservatism\n}", None, None),
    "empire": ("나폴레옹 제국", "napoleon", None, "democratic", None, None, "LR_NAP_coronation"),
    "guardian": ("공화국의 수호자", "napoleon", None, "democratic", None, None, "LR_NAP_guardian"),
    "red": ("붉은 나폴레옹", "napoleon", None, "democratic", None, None, "LR_NAP_red"),
    "petain": ("페탱의 프랑스국", "petain", "petain", "neutrality", "promote_character = LR_FRA_petain", "LR_FRA_etat", None),
    "vanquished": ("패전 후 점령기", "vanquished", None, "neutrality", "set_variable = { LR_resist = 10 }", None, None),
}
NAPOLEON_ROADS = {"empire", "guardian", "red"}


def indent(text, tabs):
    pad = "\t" * tabs
    return "\n".join(pad + line for line in text.split("\n"))


def decision(route):
    name, regime, ruler, government, leader, cosmetic, fork = ROUTES[route]
    lines = [f"clr_country_flag = LR_route_{r}" for r in ALL_ROUTES]
    lines += ["drop_cosmetic_tag = yes", f"lr_fra_regime_{regime} = yes", f"lr_fra_ruler_{ruler or 'none'} = yes",
              f"set_politics = {{\n\truling_party = {government}\n\telections_allowed = {'yes' if government == 'democratic' else 'no'}\n}}"]
    if route in NAPOLEON_ROADS:
        # His roads hang under the trunk: show it, then take the fork, whose effects do the rest.
        lines += ["set_country_flag = LR_route_napoleon", f"complete_national_focus = {fork}"]
    else:
        lines.append(f"set_country_flag = LR_route_{route}")
    if leader:
        lines.append(leader)
    if cosmetic:
        lines.append(f"set_cosmetic_tag = {cosmetic}")
    lines.append("mark_focus_tree_layout_dirty = yes")
    body = indent("\n".join(lines), 3)
    return (f"\tLR_dec_debug_{route} = {{\n\t\ticon = generic_research\n\t\tcost = 0\n\t\tfire_only_once = no\n"
            f"\t\tvisible = {{ is_debug = yes }}\n\t\tcomplete_effect = {{\n{body}\n\t\t}}\n\t\tai_will_do = {{ factor = 0 }}\n\t}}"), name


def main():
    blocks, loc = [], ['l_korean:', ' LR_FRA_debug_category:0 "디버그: 루트 불러오기"',
                       ' LR_FRA_debug_category_desc:0 "디버그 모드에서만 보입니다. 루트 플래그를 바꾸고 그 루트의 중점을 바로 엽니다. 정부와 지도자, 정권 정신도 함께 바뀝니다."']
    for route in ROUTES:
        block, name = decision(route)
        blocks.append(block)
        loc.append(f' LR_dec_debug_{route}:0 "루트: {name}"')
        loc.append(f' LR_dec_debug_{route}_desc:0 "모든 루트 플래그를 지우고 §Y{name}§! 루트의 중점을 엽니다."')
    folder = MOD / "common" / "decisions"
    (folder / "lr_debug_decisions.txt").write_text(NOTE + "LR_FRA_debug_category = {\n" + "\n".join(blocks) + "\n}\n", encoding="utf-8")
    (folder / "categories" / "lr_debug_categories.txt").write_text(
        NOTE + "LR_FRA_debug_category = {\n\ticon = generic_research\n\tpriority = 0\n\tvisible = {\n\t\tis_debug = yes\n\t\ttag = FRA\n\t}\n}\n", encoding="utf-8")
    (MOD / "localisation" / "korean" / "lr_debug_l_korean.yml").write_text("\n".join(loc) + "\n", encoding="utf-8-sig")
    print(f"OK: {len(ROUTES)} debug route decisions")


if __name__ == "__main__":
    main()
