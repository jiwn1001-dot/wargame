"""No vanilla diplomacy: the world of 1936 starts with the alliances this mod writes, and nothing else.

Vanilla country histories create the Allies, the Axis and the Comintern, hand out guarantees (France to
Czechoslovakia, Britain and France to Belgium), military access, non-aggression pacts, opinion modifiers and a
few wars. This copies every vanilla history file that has any of these into the mod with those statements cut
out, so the rest of the history (leaders, laws, units, subjects) stays as vanilla wrote it.
Subjects (puppet, set_autonomy) are kept: the British dominions and the like are part of this world.
build_systems.py calls main().
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD = world.MOD
VANILLA = world.VANILLA
CUT = ("create_faction_from_template", "create_faction", "add_to_faction", "give_guarantee", "give_military_access",
       "diplomatic_relation", "create_wargoal", "declare_war_on", "add_opinion_modifier", "reverse_add_opinion_modifier")
KEY = re.compile(r"\b(" + "|".join(CUT) + r")\s*=\s*")


def comment_mask(text):
    """True for every character inside a # comment (quotes are respected)."""
    mask = [False] * len(text)
    quoted = False
    i = 0
    while i < len(text):
        c = text[i]
        if c == '"':
            quoted = not quoted
        elif c == "#" and not quoted:
            j = text.find("\n", i)
            j = len(text) if j < 0 else j
            for k in range(i, j):
                mask[k] = True
            i = j
            continue
        elif c == "\n":
            quoted = False
        i += 1
    return mask


def value_end(text, start, mask):
    """End of the value that starts at start: a braced block, a quoted string or a single word."""
    if text[start] == "{":
        depth = 0
        for i in range(start, len(text)):
            if mask[i]:
                continue
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    return i + 1
        raise ValueError("unbalanced braces")
    if text[start] == '"':
        return text.index('"', start + 1) + 1
    m = re.match(r"[^\s{}#]+", text[start:])
    return start + m.end()


def strip(text):
    mask = comment_mask(text)
    cuts = []
    for m in KEY.finditer(text):
        if mask[m.start()] or (cuts and m.start() < cuts[-1][1]):
            continue
        cuts.append((m.start(), value_end(text, m.end(), mask)))
    for start, end in reversed(cuts):
        text = text[:start] + text[end:]
    return text, len(cuts)


def main():
    out = MOD / "history" / "countries"
    out.mkdir(parents=True, exist_ok=True)
    files = removed = 0
    for path in sorted((VANILLA / "history" / "countries").glob("*.txt")):
        if (out / path.name).exists() and "Generated by tools/build_diplomacy.py" not in (out / path.name).read_text(encoding="utf-8-sig", errors="ignore")[:200]:
            continue  # a history the mod writes itself
        raw = path.read_bytes()
        text = raw.decode("utf-8-sig", errors="replace")
        new, count = strip(text)
        if not count:
            continue
        assert new.count("{") == new.count("}"), path.name
        (out / path.name).write_bytes(("﻿# Generated by tools/build_diplomacy.py from the vanilla file: vanilla diplomacy removed.\n" + new).encode("utf-8"))
        files += 1
        removed += count
    print(f"OK: vanilla diplomacy removed, {removed} statements in {files} country histories")


if __name__ == "__main__":
    main()
