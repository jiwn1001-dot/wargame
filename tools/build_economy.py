# ---------- Hand evaluation, written once as steps so the game script and a Python check share it ----------
def evaluate(cards):
    """The same algorithm the game runs: category, highest rank, second rank. Ranks 0-12 (2 to ace)."""
    rc = [0] * 13
    sc = [0] * 4
    sr = [[0] * 13 for _ in range(4)]
    for c in cards:
        rc[c % 13] += 1
        sc[c // 13] += 1
        sr[c // 13][c % 13] = 1
    fs = next((s for s in range(4) if sc[s] > 4), -1)
    t = next((r for r in range(12, -1, -1) if rc[r] > 2), -1)
    p1 = p2 = -1
    for r in range(12, -1, -1):
        if rc[r] > 1 and r != t:
            if p1 < 0:
                p1 = r
            elif p2 < 0:
                p2 = r

    def run(present, top):
        ranks = [top - i for i in range(5)] if top > 3 else [3, 2, 1, 0, 12]
        return all(present[r] for r in ranks)

    def highest_other(exclude):
        return next(r for r in range(12, -1, -1) if rc[r] > 0 and r != exclude)

    for s in range(4):
        for top in range(12, 2, -1):
            if run(sr[s], top):
                return 8, top, 0
    for r in range(12, -1, -1):
        if rc[r] == 4:
            return 7, r, highest_other(r)
    if t >= 0 and p1 >= 0:
        return 6, t, p1
    if fs >= 0:
        flush = [r for r in range(12, -1, -1) if sr[fs][r]]
        return 5, flush[0], flush[1]
    for top in range(12, 2, -1):
        if run(rc, top):
            return 4, top, 0
    if t >= 0:
        return 3, t, highest_other(t)
    if p2 >= 0:
        return 2, p1, p2
    if p1 >= 0:
        return 1, p1, highest_other(p1)
    present = [r for r in range(12, -1, -1) if rc[r]]
    return 0, present[0], present[1]


def true_category(cards):
    """A brute-force check: the best category over every five of the seven cards."""
    best = 0
    for five in itertools.combinations(cards, 5):
        ranks = sorted((c % 13 for c in five), reverse=True)
        counts = sorted((ranks.count(r) for r in set(ranks)), reverse=True)
        flush = len({c // 13 for c in five}) == 1
        straight = len(set(ranks)) == 5 and (ranks[0] - ranks[4] == 4 or ranks == [12, 3, 2, 1, 0])
        category = (8 if straight and flush else 7 if counts[0] == 4 else 6 if counts[:2] == [3, 2] else 5 if flush
                    else 4 if straight else 3 if counts[0] == 3 else 2 if counts[:2] == [2, 2] else 1 if counts[0] == 2 else 0)
        best = max(best, category)
    return best


def check_evaluator(rounds=20000):
    rng = random.Random(1)
    for _ in range(rounds):
        cards = rng.sample(range(52), 7)
        if evaluate(cards)[0] != true_category(cards):
            raise SystemExit(f"hand evaluator is wrong for {cards}: {evaluate(cards)} vs {true_category(cards)}")


