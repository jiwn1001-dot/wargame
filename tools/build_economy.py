def card_sheet():
    """53 frames side by side: the 52 cards, then the back."""
    width, height = CARD
    sheet = Image.new("RGBA", (width * 53, height), (0, 0, 0, 0))
    symbols = ImageFont.truetype(r"C:\Windows\Fonts\seguisym.ttf", 22)
    small = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 13)
    for card in range(53):
        face = Image.new("RGBA", CARD, (0, 0, 0, 0))
        draw = ImageDraw.Draw(face)
        if card == 52:
            draw.rounded_rectangle((0, 0, width - 1, height - 1), radius=4, fill=(120, 24, 30, 255), outline=(20, 8, 8, 255), width=2)
            for y in range(6, height - 6, 6):
                draw.line((5, y, width - 6, y), fill=(160, 60, 64, 255))
            draw.rectangle((4, 4, width - 5, height - 5), outline=(200, 170, 110, 255))
        else:
            rank, suit = card % 13, card // 13
            colour = (190, 20, 20, 255) if suit in (1, 2) else (20, 20, 24, 255)
            draw.rounded_rectangle((0, 0, width - 1, height - 1), radius=4, fill=(246, 242, 232, 255), outline=(30, 30, 30, 255), width=2)
            draw.text((4, 2), RANK_SHOWN[rank], font=small, fill=colour)
            draw.text((width // 2, height // 2 + 6), SUITS[suit], font=symbols, fill=colour, anchor="mm")
        sheet.alpha_composite(face, (card * width, 0))
    folder = MOD / "gfx" / "interface" / "lr"
    folder.mkdir(parents=True, exist_ok=True)
    sheet.save(folder / "lr_cards.dds")


