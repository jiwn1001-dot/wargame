"""A taller event window, so a scene can run long on one page instead of being split across several.

Vanilla cuts the description of a report event at 230 pixels (about 14 lines, roughly 450 Korean characters).
This copies vanilla interface/eventwindow.gui with the description allowed to grow to DESC_HEIGHT; the tileable
midsection stretches with it and the bottom section moves down. The window is raised so it still fits a 1080p
screen. build_systems.py calls main().
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD = world.MOD
VANILLA = world.VANILLA
DESC_HEIGHT = 480  # 30 lines of hoi4_typewriter16: about 950 characters with paragraph breaks
RAISE = 90  # pixels the window moves up to make room


def main():
    text = (VANILLA / "interface" / "eventwindow.gui").read_text(encoding="utf-8-sig")
    start = text.index('name = "EventWindow"')
    end = text.index('name = "EventWindow_Operative"')
    block = text[start:end]
    old_pos = "position = { x=-282 y=-310 }"
    old_desc = "maxWidth = 512\n\t\t\t\tmaxHeight = 230"
    assert block.count(old_pos) == 1 and block.count(old_desc) == 1, "vanilla eventwindow.gui changed"
    block = block.replace(old_pos, f"position = {{ x=-282 y={-310 - RAISE} }}")
    block = block.replace(old_desc, f"maxWidth = 512\n\t\t\t\tmaxHeight = {DESC_HEIGHT}")
    out = MOD / "interface" / "eventwindow.gui"
    out.write_text("# Generated by tools/build_eventwindow.py: taller event descriptions.\n" + text[:start] + block + text[end:], encoding="utf-8")
    print(f"OK: event descriptions up to {DESC_HEIGHT}px")


if __name__ == "__main__":
    main()
