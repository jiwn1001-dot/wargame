"""Armies, fleets and air forces for this world.

1. Vanilla orders of battle place units where vanilla borders run. Every land division, fleet and air wing that now
   stands on another country's soil is moved home: divisions to the capital, fleets to the country's largest naval
   base, air wings to its largest air base. The moved files go to mod/history/units under their vanilla names.
2. Size: Russia's republic, without the Red Army's build-up, keeps half its divisions. France keeps its divisions
   but starts green: a budget-starved army under political generals.
3. The victors raise more divisions at the start (lr_world_armies, called from lr_world_startup): the Habsburg
   empire, the Ottoman empire and the two Germanies.
build_systems.py calls main().
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD, VANILLA = world.MOD, world.VANILLA
NOTE = "# Generated by tools/build_oob.py from the vanilla file: units moved home, sizes for this world.\n"
KEEP_SHARE = {"SOV": 0.5}  # share of land divisions kept
GREEN = {"FRA": 0.1}  # start experience
# tag: (template name, divisions, start experience)
RAISE = {
    "AUS": ("LR Imperial Infantry", 36, 0.3),
    "TUR": ("LR Nizam Infantry", 18, 0.2),
    "GER": ("LR Prussian Infantry", 20, 0.4),
    "BAY": ("LR Bavarian Infantry", 12, 0.3),
}


def read_states():
    states = {}
    for path in (VANILLA / "history" / "states").glob("*.txt"):
        text = re.sub(r"#.*", "", path.read_text(encoding="utf-8-sig", errors="ignore"))
        sid = int(re.search(r"\bid\s*=\s*(\d+)", text).group(1))
        head = re.split(r"\n\s*\d{4}\.\d+\.\d+\s*=", text)[0]
        owner = re.search(r"\bowner\s*=\s*(\w+)", head)
        provinces = [int(p) for p in re.search(r"provinces\s*=\s*\{([^}]*)\}", text).group(1).split()] if "provinces" in text else []
        air = re.search(r"\bair_base\s*=\s*(\d+)", head)
        ports = [(int(level), int(prov)) for prov, level in re.findall(r"(\d+)\s*=\s*\{\s*naval_base\s*=\s*(\d+)", head)]
        states[sid] = {"owner": owner.group(1) if owner else None, "provinces": provinces,
                       "air": int(air.group(1)) if air else 0, "ports": ports}
    for tag, moved in world.TRANSFERS.items():
        for sid in moved:
            if sid in states:
                states[sid]["owner"] = tag
    return states


def capitals():
    caps = {}
    for path in (VANILLA / "history" / "countries").glob("*.txt"):
        found = re.search(r"^capital\s*=\s*(\d+)", path.read_text(encoding="utf-8-sig", errors="ignore"), re.M)
        if found:
            caps[path.name[:3]] = int(found.group(1))
    return caps


def homes(states, caps):
    """tag -> (capital province, best naval base province, best air base state)."""
    owned = {}
    for sid, s in states.items():
        if s["owner"]:
            owned.setdefault(s["owner"], []).append(sid)
    out = {}
    for tag, sids in owned.items():
        cap = caps.get(tag)
        cap_state = cap if cap in sids else max(sids, key=lambda s: len(states[s]["provinces"]))
        cap_prov = states[cap_state]["provinces"][0] if states[cap_state]["provinces"] else None
        ports = sorted((lvl, prov) for s in sids for lvl, prov in states[s]["ports"])
        air = max(sids, key=lambda s: (states[s]["air"], s == cap_state))
        out[tag] = (cap_prov, ports[-1][1] if ports else None, air if states[air]["air"] else None)
    return out


def blocks(text, word):
    """(start, end) of every 'word = { ... }' block, braces matched."""
    out = []
    for m in re.finditer(rf"\b{word}\s*=\s*\{{", text):
        depth, i = 0, m.end() - 1
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    out.append((m.start(), i + 1))
                    break
            i += 1
    return out


def main():
    states = read_states()
    prov_state = {p: sid for sid, s in states.items() for p in s["provinces"]}
    home = homes(states, capitals())
    out_dir = MOD / "history" / "units"
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.txt"):
        if NOTE.strip() in old.read_text(encoding="utf-8-sig", errors="ignore")[:200]:
            old.unlink()

    def foreign(tag, prov):
        sid = prov_state.get(int(prov))
        return sid is not None and states[sid]["owner"] != tag

    moved = files = 0
    for path in sorted((VANILLA / "history" / "units").glob("*.txt")):
        tag = path.name[:3]
        if tag not in home:
            continue  # a country that does not exist in this world
        cap_prov, port, air_state = home[tag]
        text = path.read_text(encoding="utf-8-sig", errors="ignore")
        new = text
        name = path.name.lower()
        if "naval" in name:
            if port:
                def fix(m):
                    nonlocal moved
                    if foreign(tag, m.group(2)):
                        moved += 1
                        return f"{m.group(1)}{port}"
                    return m.group(0)
                new = re.sub(r"(\b(?:location|naval_base)\s*=\s*)(\d+)", fix, new)
        elif "air" in name:
            if air_state:
                def fix_air(m):
                    nonlocal moved
                    sid = int(m.group(2))
                    if sid in states and states[sid]["owner"] != tag:
                        moved += 1
                        return f"{m.group(1)}{air_state}{m.group(3)}"
                    return m.group(0)
                new = re.sub(r"(\n\t)(\d+)(\s*=\s*\{)", fix_air, new)
        elif cap_prov:
            spans = blocks(new, "division")
            keep = KEEP_SHARE.get(tag)
            pieces, last, count = [], 0, 0
            for start, end in spans:
                block = new[start:end]
                count += 1
                if keep is not None and (count % round(1 / keep)) != 0:
                    pieces.append(new[last:start])  # dropped
                    last = end
                    continue

                def fix_loc(m):
                    nonlocal moved
                    if foreign(tag, m.group(2)):
                        moved += 1
                        return f"{m.group(1)}{cap_prov}"
                    return m.group(0)
                block = re.sub(r"(\blocation\s*=\s*)(\d+)", fix_loc, block)
                if tag in GREEN:
                    if "start_experience_factor" in block:
                        block = re.sub(r"start_experience_factor\s*=\s*[\d.]+", f"start_experience_factor = {GREEN[tag]}", block)
                    else:
                        block = block[:-1].rstrip() + f"\n\t\tstart_experience_factor = {GREEN[tag]}\n\t}}"
                pieces.append(new[last:start] + block)
                last = end
            pieces.append(new[last:])
            new = "".join(pieces)
        if new != text:
            (out_dir / path.name).write_text(NOTE + new, encoding="utf-8")
            files += 1

    effect = ["# Generated by tools/build_oob.py: the victors' larger armies.", "lr_world_armies = {"]
    for tag, (template, count, xp) in RAISE.items():
        effect.append(f"\t{tag} = {{\n\t\tdivision_template = {{\n\t\t\tname = \"{template}\"\n\t\t\tregiments = {{\n"
                      "\t\t\t\tinfantry = { x = 0 y = 0 }\n\t\t\t\tinfantry = { x = 0 y = 1 }\n\t\t\t\tinfantry = { x = 0 y = 2 }\n"
                      "\t\t\t\tinfantry = { x = 1 y = 0 }\n\t\t\t\tinfantry = { x = 1 y = 1 }\n\t\t\t\tinfantry = { x = 1 y = 2 }\n"
                      "\t\t\t\tinfantry = { x = 2 y = 0 }\n\t\t\t\tinfantry = { x = 2 y = 1 }\n\t\t\t\tinfantry = { x = 2 y = 2 }\n\t\t\t}\n\t\t}\n"
                      # create_unit runs in a state scope: the divisions appear in the capital.
                      f"\t\tcapital_scope = {{\n\t\t\tfor_loop_effect = {{\n\t\t\t\tend = {count}\n\t\t\t\tcreate_unit = {{\n"
                      f"\t\t\t\t\tdivision = \"division_template = \\\"{template}\\\" start_experience_factor = {xp}\"\n"
                      f"\t\t\t\t\towner = {tag}\n\t\t\t\t}}\n\t\t\t}}\n\t\t}}\n\t}}")
    effect.append("}")
    (MOD / "common" / "scripted_effects" / "lr_armies_effects.txt").write_text("\n".join(effect) + "\n", encoding="utf-8")
    # Countries vanilla leaves out at the start but this world has (Ukraine, Belarus, the Caucasus): their history names
    # an order of battle vanilla never wrote. Give each a small army at its capital.
    raised = []
    for path in sorted((VANILLA / "history" / "countries").glob("*.txt")):
        tag = path.name[:3]
        oob = re.search(r'^oob\s*=\s*"(\w+)"', path.read_text(encoding="utf-8-sig", errors="ignore"), re.M)
        if not oob or tag not in home or not home[tag][0]:
            continue
        if (VANILLA / "history" / "units" / f"{oob.group(1)}.txt").exists() or (out_dir / f"{oob.group(1)}.txt").exists():
            continue
        divisions = "".join(f'\tdivision = {{\n\t\tname = "{n}. Infantry"\n\t\tlocation = {home[tag][0]}\n\t\tdivision_template = "LR Militia"\n'
                            "\t\tstart_experience_factor = 0.1\n\t}\n" for n in range(1, 5))
        (out_dir / f"{oob.group(1)}.txt").write_text(
            NOTE + 'division_template = {\n\tname = "LR Militia"\n\tregiments = {\n\t\tinfantry = { x = 0 y = 0 }\n\t\tinfantry = { x = 0 y = 1 }\n'
            "\t\tinfantry = { x = 1 y = 0 }\n\t\tinfantry = { x = 1 y = 1 }\n\t}\n}\nunits = {\n" + divisions + "}\n", encoding="utf-8")
        raised.append(tag)
    if raised:
        print(f"OK: small armies for {', '.join(raised)}")
    print(f"OK: {moved} units moved home in {files} order-of-battle files; Russia keeps half its divisions; "
          f"{sum(r[1] for r in RAISE.values())} divisions raised for the victors")


if __name__ == "__main__":
    main()
