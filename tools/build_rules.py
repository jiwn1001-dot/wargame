"""Game rules for every country, written into the ideologies rather than as national spirits.

1. War only by focus and event. No ideology can justify a war goal (the world tension it needs is set beyond the
   100% maximum) or declare war without one, so the diplomacy screen offers no war. Focuses, events and the war-plan
   decisions use declare_war_on, which needs no war goal, so they still start wars.
2. No limits on volunteers: every ideology may send them at any tension, with no division minimum, no cooldown
   and a much larger cap (defines).
build_systems.py calls main().
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD = world.MOD
VANILLA = world.VANILLA

DEFINES = """-- Generated by tools/build_rules.py: volunteers without limits.
NDefines.NDiplomacy.VOLUNTEERS_DIVISIONS_REQUIRED = 0
NDefines.NDiplomacy.VOLUNTEERS_PER_TARGET_PROVINCE = 1.0
NDefines.NDiplomacy.VOLUNTEERS_PER_COUNTRY_ARMY = 1.0
NDefines.NDiplomacy.SEND_VOLUNTEERS_AGAIN_COOLDOWN = 0
NDefines.NDiplomacy.RECALL_VOLUNTEERS_AFTER_ARRIVAL_COOLDOWN = 0
NDefines.NDiplomacy.TENSION_VOLUNTEER_FORCE_DIVISION = 0
NDefines.NCountry.AIR_VOLUNTEER_PLANES_RATIO = 1.0
NDefines.NCountry.AIR_VOLUNTEER_BASES_CAPACITY_LIMIT = 1.0
"""


def main():
    text = (VANILLA / "common" / "ideologies" / "00_ideologies.txt").read_text(encoding="utf-8-sig")
    rules = len(re.findall(r"\brules = \{", text))
    # Volunteers: everyone may send them, at any tension.
    text = re.sub(r"can_send_volunteers = no", "can_send_volunteers = yes", text)
    text = re.sub(r"send_volunteers_tension = [\d.]+", "send_volunteers_tension = 0", text)
    # War: no war goal can ever be justified, and none can be skipped.
    text = re.sub(r"generate_wargoal_tension = [\d.]+", "generate_wargoal_tension = 2.0", text)
    text = re.sub(r"can_declare_war_without_wargoal_when_in_war = yes", "can_declare_war_without_wargoal_when_in_war = no", text)
    added = 0

    def add_rules(m):
        nonlocal added
        block = m.group(0)
        extra = []
        if "can_send_volunteers" not in block:
            extra.append("can_send_volunteers = yes")
        if "can_declare_war_without_wargoal_when_in_war" not in block:
            extra.append("can_declare_war_without_wargoal_when_in_war = no")
        added += bool(extra)
        return block + "".join(f"\n\t\t\t{e}" for e in extra)

    text = re.sub(r"rules = \{", add_rules, text)

    def add_tension(m):
        block = m.group(0)
        if "generate_wargoal_tension" not in block:
            block += "\n\t\t\tgenerate_wargoal_tension = 2.0"
        if "send_volunteers_tension" not in block:
            block += "\n\t\t\tsend_volunteers_tension = 0"
        return block

    text = re.sub(r"\n\t\tmodifiers = \{", add_tension, text)
    assert text.count("{") == text.count("}")
    out = MOD / "common" / "ideologies" / "00_ideologies.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Generated by tools/build_rules.py from the vanilla file: war only by focus and event, volunteers unlimited.\n" + text, encoding="utf-8")
    defines = MOD / "common" / "defines" / "lr_defines.lua"
    defines.parent.mkdir(parents=True, exist_ok=True)
    defines.write_text(DEFINES, encoding="utf-8")
    print(f"OK: rules for {rules} ideologies (war only by focus and event, volunteers unlimited)")


if __name__ == "__main__":
    main()
