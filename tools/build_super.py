def loudest_start(source, length):
    """Seconds into the recording where the loudest `length`-second stretch begins, skipping the first 3 seconds.

    Most of these recordings are mastered loud all the way through, so this is only a guess: a song whose climax it
    misses gets its start in seconds in SUPER_EVENTS ("cut": {"start": 95, ...})."""
    import imageio_ffmpeg
    rate = 8000
    raw = subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-v", "error", "-i", str(source), "-ac", "1", "-ar", str(rate), "-f", "s16le", "-"],
                         capture_output=True, check=True).stdout
    samples = np.frombuffer(raw, dtype=np.int16).astype(float)
    step = rate // 2  # half-second blocks
    blocks = np.sqrt(np.array([np.mean(samples[i:i + step] ** 2) for i in range(0, len(samples) - step, step)]) + 1e-9)
    width = int(length * 2)
    if len(blocks) <= width + 6:
        return 0.0
    sums = np.convolve(blocks, np.ones(width), mode="valid")
    best = int(np.argmax(sums[6:])) + 6
    return best / 2


def cut_song(row):
    """Trim the source recording: start at the verse, at most the given length, fading away at the end."""
    cut = row.get("cut")
    sources = sorted(ART.glob(f"super_{row['key']}_source.*"))
    if not cut or not sources:
        return
    # The cut is redone only when the recording or the cut settings change: ffmpeg is the slowest part of the build.
    target = ART / f"super_{row['key']}.ogg"
    stamp = ART / f"super_{row['key']}.cut"
    source_stat = sources[0].stat()
    key = f"{sources[0].name} {source_stat.st_size} {int(source_stat.st_mtime)} {sorted(cut.items())}"
    if target.exists() and stamp.exists() and stamp.read_text(encoding="utf-8") == key:
        return
    import imageio_ffmpeg
    fade_from = cut["length"] - cut["fade"]
    start = loudest_start(sources[0], cut["length"]) if cut["start"] == "auto" else cut["start"]
    print(f"  {row['key']}: song from {start:.1f}s")
    subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-y", "-v", "error", "-ss", str(start), "-t", str(cut["length"]), "-i", str(sources[0]),
                    "-af", f"afade=t=in:st=0:d=0.5,afade=t=out:st={fade_from}:d={cut['fade']},loudnorm=I=-14:TP=-1.5",
                    # loudnorm resamples to 192 kHz; the game wants 44.1 kHz
                    "-ar", "44100", "-c:a", "libvorbis", "-q:a", "5", str(target)], check=True)
    stamp.write_text(key, encoding="utf-8")


def build_music():
    entries = []
    for row in SUPER_EVENTS:
        cut_song(row)
        own = ART / f"super_{row['key']}.ogg"
        if own.exists():
            target = MOD / "music" / f"lr_super_{row['key']}.ogg"
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists() or target.stat().st_size != own.stat().st_size or target.stat().st_mtime < own.stat().st_mtime:
                shutil.copy2(own, target)
            entries.append(f'music = {{\n\tname = "lr_super_{row["key"]}"\n\tfile = "lr_super_{row["key"]}.ogg"\n\tvolume = 0.65\n}}\n')
    path = MOD / "music" / "lr_music.asset"
    songs = MOD / "music" / "lr_songs.txt"
    if entries:
        write(path, NOTE + "".join(entries))
        names = [row["key"] for row in SUPER_EVENTS if (ART / f"super_{row['key']}.ogg").exists()]
        block = 'music = {{\n\tsong = "lr_super_{}"\n\tchance = {{\n\t\tmodifier = {{\n\t\t\tfactor = 0\n\t\t}}\n\t}}\n}}\n'
        write(songs, NOTE + 'music_station = "base_music"\n\n' + "".join(block.format(name) for name in names))
    else:
        path.unlink(missing_ok=True)
        songs.unlink(missing_ok=True)


