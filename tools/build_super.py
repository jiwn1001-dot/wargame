def shade_for_quote(picture):
    """Darken the lower right of the picture so the quote reads over it."""
    width, height = picture.size
    band = Image.new("RGBA", picture.size, (0, 0, 0, 0))
    pixels = band.load()
    top, fade_from, fade_to = round(height * 0.68), round(width * 0.12), round(width * 0.38)
    for x in range(width):
        strength = 0 if x < fade_from else 1 if x > fade_to else (x - fade_from) / (fade_to - fade_from)
        for y in range(top, height):
            pixels[x, y] = (0, 0, 0, round(165 * strength))
    picture.alpha_composite(band)
    return picture


