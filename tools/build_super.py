def write(path, text, encoding="utf-8"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding=encoding)


def planks(width, height, plank_height, dark=(58, 36, 20), light=(112, 74, 42), seed=7):
    """Dark walnut boards: long wavy grain, a different tone per board, and seams between them."""
    rng = np.random.default_rng(seed)
    ys, xs = np.mgrid[0:height, 0:width]
    pixels = np.zeros((height, width, 3), dtype=float)
    for board in range(height // plank_height + 1):
        top = board * plank_height
        mask = (ys >= top) & (ys < top + plank_height)
        phase, offset, tone = rng.uniform(0, 6.28), rng.uniform(0, 400), rng.uniform(-0.12, 0.12)
        grain = (np.sin((ys * 0.9 + 9 * np.sin((xs + offset) * 0.008 + phase)) * 0.75)
                 + 0.5 * np.sin((ys * 2.3 + 4 * np.sin((xs + offset) * 0.021)) * 0.9)
                 + 0.25 * np.sin(ys * 5.1 + xs * 0.03)) / 1.75
        share = np.clip(0.5 + 0.42 * grain + tone, 0, 1)
        for channel in range(3):
            pixels[..., channel] = np.where(mask, dark[channel] + (light[channel] - dark[channel]) * share, pixels[..., channel])
        seam = (ys == top) | (ys == top + 1)
        pixels[seam] = pixels[seam] * 0.45
    pixels += rng.normal(0, 3, (height, width, 1))
    return Image.fromarray(np.clip(pixels, 0, 255).astype("uint8"), "RGB").convert("RGBA").filter(ImageFilter.GaussianBlur(0.4))


def bevel(image, thickness):
    """A carved edge: light on the upper left, shadow on the lower right."""
    overlay = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    width, height = image.size
    for step in range(thickness):
        fade = 1 - step / thickness
        draw.line([(step, height - 1 - step), (step, step), (width - 1 - step, step)], fill=(226, 186, 132, round(90 * fade)))
        draw.line([(step, height - 1 - step), (width - 1 - step, height - 1 - step), (width - 1 - step, step)], fill=(16, 8, 2, round(150 * fade)))
    image.alpha_composite(overlay)


def steel(width, height, base=(58, 62, 58), seed=11):
    """Brushed gunmetal: fine horizontal streaks and a little noise, like a 1940s instrument panel."""
    rng = np.random.default_rng(seed)
    streak = rng.normal(0, 6, (height, 1)) + rng.normal(0, 2.5, (height, width))
    pixels = np.array(base, dtype=float)[None, None, :] + streak[..., None]
    return Image.fromarray(np.clip(pixels, 0, 255).astype("uint8"), "RGB").convert("RGBA")


def rivets(draw, points):
    for cx, cy in points:
        draw.ellipse((cx - 4, cy - 4, cx + 4, cy + 4), fill=(44, 46, 42, 255), outline=(14, 14, 12, 255))
        draw.ellipse((cx - 2, cy - 3, cx, cy - 1), fill=(150, 150, 140, 255))


def plate(draw, box, fill=(46, 46, 50, 255)):
    """A dark grey metal plate with a light upper edge and a dark lower edge."""
    x0, y0, x1, y1 = box
    draw.rectangle(box, fill=fill, outline=(12, 12, 14, 255), width=2)
    draw.line((x0 + 2, y0 + 2, x1 - 2, y0 + 2), fill=(110, 110, 116, 255))
    draw.line((x0 + 2, y1 - 2, x1 - 2, y1 - 2), fill=(20, 20, 22, 255))


def knob(draw, cx, cy, r=14):
    """A round steel knob, shaded from the top left."""
    for step in range(r, 0, -1):
        shade = round(60 + 150 * (1 - step / r) ** 0.7)
        draw.ellipse((cx - step, cy - step, cx + step, cy + step), fill=(shade, shade, shade + 4, 255))
    draw.ellipse((cx - r, cy - r, cx + r, cy + r), outline=(14, 14, 16, 255), width=2)
    draw.ellipse((cx - r // 3 - 2, cy - r // 3 - 2, cx - r // 3 + 2, cy - r // 3 + 2), fill=(235, 235, 240, 255))


