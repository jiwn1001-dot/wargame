def build_blocks():
    """Switch off every vanilla decision category without touching the decision files."""
    decisions = VANILLA / "common" / "decisions"
    blocked = set()
    for path in (decisions / "categories").glob("*.txt"):
        source = re.sub(r"#.*", "", path.read_text(encoding="utf-8-sig", errors="ignore"))
        blocked |= set(re.findall(r"^(\w+)\s*=\s*\{", source, re.M))

    found = set()
    for path in (decisions / "categories").glob("*.txt"):
        text = path.read_text(encoding="utf-8-sig", errors="ignore")
        here = [m for m in re.finditer(r"^(\w+)\s*=\s*\{", text, re.M) if m.group(1) in blocked]
        if not here:
            continue
        for match in reversed(here):
            found.add(match.group(1))
            start = match.end()
            depth, end = 1, start
            while depth:
                depth += {"{": 1, "}": -1}.get(text[end], 0)
                end += 1
            body = text[start:end - 1]
            # Remove any existing allowed block, then forbid the category outright.
            at = re.search(r"\ballowed\s*=\s*\{", body)
            if at:
                inner, stop = 1, at.end()
                while inner:
                    inner += {"{": 1, "}": -1}.get(body[stop], 0)
                    stop += 1
                body = body[:at.start()] + body[stop:]
            text = text[:start] + "\n\tallowed = { always = no }" + body + text[end - 1:]
        write(MOD / "common" / "decisions" / "categories" / path.name, text)
    missing = blocked - found
    return len(found), sorted(missing)


def build_quiet_events():
    """Vanilla events are written for our history. Each vanilla event file is replaced by one that only
    declares its namespaces, so nothing in it can fire; the game logs references to the missing events."""
    count = 0
    for path in (VANILLA / "events").glob("*.txt"):
        text = path.read_text(encoding="utf-8-sig", errors="ignore")
        spaces = sorted(set(re.findall(r"^\s*add_namespace\s*=\s*([\w.]+)", text, re.M)))
        write(MOD / "events" / path.name, NOTE + "# Vanilla events switched off.\n" + "".join(f"add_namespace = {s}\n" for s in spaces))
        count += 1
    return count


