def indent(text, tabs):
    return "\n".join("\t" * tabs + line for line in text.split("\n"))


def write(path, text, encoding="utf-8"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding=encoding)


def check_regions():
    """Every listed state must be French after the world setup, and listed once."""
    final = dict(world.vanilla_states())
    for tag, states in world.TRANSFERS.items():
        for state in states:
            final[state] = tag
    seen = set()
    for key, _, states, _, _ in REGIONS:
        for state in states:
            if final.get(state) != "FRA":
                raise SystemExit(f"region {key}: state {state} belongs to {final.get(state)}, not FRA")
            if state in seen:
                raise SystemExit(f"state {state} is in two regions")
            seen.add(state)
    return len(seen)


DOT = 6  # Pixels per seat dot.


def hemicycle():
    """One position per deputy: 610 seats in twelve arcs, numbered left to right like the Chamber."""
    seats = []
    radii = [70 + 15 * row for row in range(12)]
    share = [round(SEATS_TOTAL * r / sum(radii)) for r in radii]
    share[-1] += SEATS_TOTAL - sum(share)
    for radius, count in zip(radii, share):
        for i in range(count):
            angle = math.pi - math.pi * (i + 0.5) / count
            seats.append((angle, 245 + radius * math.cos(angle), 268 - radius * math.sin(angle)))
    seats.sort(key=lambda s: -s[0])
    return [(round(x) - DOT // 2, round(y) - DOT // 2) for _, x, y in seats]


