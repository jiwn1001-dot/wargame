def to_rgb(kind, values):
    if kind.lower() == "hsv":
        r, g, b = colorsys.hsv_to_rgb(*values)
        return r * 255, g * 255, b * 255
    return tuple(values)


def darken(rgb):
    h, s, v = colorsys.rgb_to_hsv(*(c / 255 for c in rgb))
    return tuple(round(c * 255) for c in colorsys.hsv_to_rgb(h, min(1, s * 1.15 + 0.05), v * 0.72))


def ui_colour(rgb):
    h, s, v = colorsys.rgb_to_hsv(*(c / 255 for c in rgb))
    return tuple(round(c * 255) for c in colorsys.hsv_to_rgb(h, s, min(1, v * 1.35)))


def build_colours():
    text = re.sub(r"#.*", "", (VANILLA / "common" / "countries" / "colors.txt").read_text(encoding="utf-8-sig"))
    blocks = re.findall(r"(\w{3})\s*=\s*\{\s*color\s*=\s*(rgb|hsv)\s*\{([^}]*)\}", text, re.I)
    lines = ["# Generated by tools/build_visual.py. Edit the tables there, not this file."]
    for tag, kind, numbers in blocks:
        values = [float(n) for n in numbers.split()]
        colour = CONCEPT_COLOURS.get(tag) or darken(to_rgb(kind, values))
        ui = ui_colour(colour)
        lines.append(f"{tag} = {{\n\tcolor = rgb {{ {colour[0]} {colour[1]} {colour[2]} }}\n"
                     f"\tcolor_ui = rgb {{ {ui[0]} {ui[1]} {ui[2]} }}\n}}")
    path = MOD / "common" / "countries" / "colors.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    tags = {tag for tag, _, _ in blocks}
    missing = sorted(set(CONCEPT_COLOURS) - tags)
    if missing:
        raise SystemExit(f"concept colours for unknown tags: {missing}")
    return len(blocks)


def build_water():
    source = (VANILLA / "gfx" / "FX" / "pdxwater.shader").read_text(encoding="utf-8-sig")
    swaps = [
        # No cube map reflection.
        ("refractiveColor = refractiveColor * ( 1.0f - fresnel ) + reflectiveColor * fresnel;",
         "refractiveColor = refractiveColor * ( 1.0f - fresnel * 0.05f ) + reflectiveColor * fresnel * 0.05f;"),
        # A deep navy sea.
        ("float3 Darkness = float3(0,0,0); ", "float3 Darkness = float3(0.008f,0.016f,0.04f); "),
        ("refractiveColor = lerp(refractiveColor, Darkness, 0.2f);",
         "refractiveColor = lerp(refractiveColor, Darkness, 0.72f);"),
        # No sun glitter.
        ("lightingProperties._SpecularColor = vec3(vSpecularIntensity);",
         "lightingProperties._SpecularColor = vec3(0.0f);"),
    ]
    for old, new in swaps:
        if old not in source:
            raise SystemExit(f"water shader changed in a patch, cannot find: {old}")
        source = source.replace(old, new)
    path = MOD / "gfx" / "FX" / "pdxwater.shader"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


def build_fill():
    """Solid country colour when zoomed out; zooming in fades back to terrain."""
    source = (VANILLA / "gfx" / "FX" / "constants.fxh").read_text(encoding="utf-8-sig")
    swaps = [
        ("GB_CAM_MIN = 100.0f", f"GB_CAM_MIN = {SOLID_FROM:.1f}f"),
        ("GB_CAM_MAX = 350.0f", f"GB_CAM_MAX = {SOLID_AT:.1f}f"),
        ("GB_CAM_MAX_FILLING_CLAMP = 0.8f", "GB_CAM_MAX_FILLING_CLAMP = 1.0f"),
        ("GB_OPACITY_FAR = 0.85f", "GB_OPACITY_FAR = 1.0f"),
        ("BORDER_LIGHT_REMOVAL_FACTOR = 0.8f", "BORDER_LIGHT_REMOVAL_FACTOR = 1.0f"),
        ("BORDER_FOW_REMOVAL_FACTOR = .8f", "BORDER_FOW_REMOVAL_FACTOR = 1.0f"),
    ]
    for old, new in swaps:
        if old not in source:
            raise SystemExit(f"constants.fxh changed in a patch, cannot find: {old}")
        source = source.replace(old, new)
    path = MOD / "gfx" / "FX" / "constants.fxh"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


def build_map_text():
    """White map names: vanilla draws dark letters with a light outline, so swap the two."""
    source = (VANILLA / "gfx" / "FX" / "mapname.shader").read_text(encoding="utf-8-sig")
    old = "vSample.a *= Transp_OffsetX.x;"
    if old not in source:
        raise SystemExit(f"map text shader changed in a patch, cannot find: {old}")
    # The baked map font (build_ui.py: Song Myung) holds white glyphs in the alpha channel. Draw them white with a
    # dark outline from the four neighbours, and let the map show through: names are drawn at OPACITY.
    fnt = (MOD / "gfx" / "fonts" / "korean" / "hoi_mapfont4.fnt").read_text(encoding="utf-8")
    width, height = (int(v) for v in re.search(r"scaleW=(\d+) scaleH=(\d+)", fnt).groups())
    opacity = 0.7
    outline = (f"float2 vPx = float2( 2.0f / {width}.0f, 2.0f / {height}.0f );\n"
               "\t\t\tfloat vRing = max( max( tex2D( DiffuseTexture, v.vTexCoord + float2( vPx.x, 0.0f ) ).a, tex2D( DiffuseTexture, v.vTexCoord - float2( vPx.x, 0.0f ) ).a ),\n"
               "\t\t\t                   max( tex2D( DiffuseTexture, v.vTexCoord + float2( 0.0f, vPx.y ) ).a, tex2D( DiffuseTexture, v.vTexCoord - float2( 0.0f, vPx.y ) ).a ) );\n"
               "\t\t\tfloat vCore = saturate( vSample.a * 1.6f );\n"
               "\t\t\tvSample.rgb = lerp( float3( 0.04f, 0.04f, 0.06f ), float3( 1.0f, 1.0f, 1.0f ), vCore );\n"
               f"\t\t\tvSample.a = saturate( max( vCore, vRing * 0.8f ) ) * {opacity}f;\n\t\t\t")
    source = source.replace(old, outline + old)
    path = MOD / "gfx" / "FX" / "mapname.shader"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


