"""War support decisions for every country. Vanilla war propaganda is blocked with the other vanilla decisions,
so bombing and casualties had no cure. build_systems.py calls main()."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD = world.MOD
NOTE = "# Generated by tools/build_war_support.py.\n"
# Vanilla's way: a decision does not raise war support, it softens what bombing, casualties and sunk convoys take
# away each week while it runs. key, name, description, the vanilla trigger and modifier it works on.
DECISIONS = [
    ("civil_defence", "민방위 동원", "방공호를 파고 소방대를 꾸리고, 폭격 맞은 거리를 시민이 직접 치웁니다. 180일 동안 폭격으로 깎이는 전쟁 지지도가 줄어듭니다.",
     "bombing"),
    ("memorial", "전몰자 추모식", "전사자의 이름을 하나하나 부르는 추모식을 엽니다. 슬픔이 분노가 되고, 분노가 각오가 됩니다. 180일 동안 사상자로 깎이는 전쟁 지지도가 줄어듭니다.",
     "casualties"),
    ("convoys", "선단 피해 보도 통제", "침몰한 수송선의 이름은 신문에 실리지 않습니다. 대신 무사히 도착한 선단의 사진이 1면에 실립니다. 180일 동안 수송선 손실로 깎이는 전쟁 지지도가 줄어듭니다.",
     "convoys"),
]
COST = 100
DAYS = 180
SOFTEN = 0.006  # vanilla's figure
# The AI takes it as vanilla does: whenever the war goes on with war support below 65%, more the worse the loss.
WORST = {"bombing": -0.20, "casualties": -0.25, "convoys": -0.29}


def decision(key, kind):
    return "\n".join([
        f"\tLR_dec_ws_{key} = {{",
        "\t\ticon = generic_propaganda",
        f"\t\tcost = {COST}",
        "\t\tfire_only_once = no",
        f"\t\tdays_remove = {DAYS}",
        "\t\tvisible = { has_war = yes }",
        f"\t\tavailable = {{ has_{kind}_war_support < 0 }}",
        "\t\tremove_trigger = { has_war = no }",
        f"\t\tmodifier = {{ weekly_{kind}_war_support = {SOFTEN} }}",
        "\t\tai_will_do = {",
        "\t\t\tbase = 0",
        "\t\t\tmodifier = { add = 10 has_war_support < 0.65 }",
        "\t\t\tmodifier = { add = 20 has_war_support < 0.5 }",
        f"\t\t\tmodifier = {{ add = 50 has_{kind}_war_support < {WORST[kind]} }}",
        "\t\t}",
        "\t}",
    ])


def main():
    lines = [NOTE + "LR_war_support_category = {"]
    loc = ["l_korean:", ' LR_war_support_category:0 "전시 여론 관리"',
           ' LR_war_support_category_desc:0 "폭격과 사상자, 수송선 손실로 전쟁 지지도가 깎이는 것을 늦춥니다. 전쟁 지지도를 직접 올리지는 않습니다."']
    for key, name, desc, kind in DECISIONS:
        lines.append(decision(key, kind))
        loc += [f' LR_dec_ws_{key}:0 "{name}"', f' LR_dec_ws_{key}_desc:0 "{desc}"']
    lines.append("}")
    (MOD / "common" / "decisions" / "lr_war_support_decisions.txt").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    (MOD / "common" / "decisions" / "categories" / "lr_war_support_categories.txt").write_bytes(
        (NOTE + "LR_war_support_category = {\n\ticon = generic_propaganda\n\tpriority = 50\n}\n").encode("utf-8"))
    (MOD / "localisation" / "korean" / "lr_war_support_l_korean.yml").write_bytes(("﻿" + "\n".join(loc) + "\n").encode("utf-8"))
    print(f"OK: {len(DECISIONS)} war support decisions")


if __name__ == "__main__":
    main()
