"""War support decisions for every country. Vanilla war propaganda is blocked with the other vanilla decisions,
so bombing and casualties had no cure. build_systems.py calls main()."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_world as world  # noqa: E402

MOD = world.MOD
NOTE = "# Generated by tools/build_war_support.py.\n"
# key, name, description, cost, days before it can be taken again, war only, effects
DECISIONS = [
    ("rally", "애국 집회", "광장에 군악대와 연사를 세웁니다. 폭격과 전사자 명단에 지친 사람들에게 이 전쟁의 이유를 다시 말합니다. 전쟁 지지도 +5%.", 50, 90, True,
     ["add_war_support = 0.05"]),
    ("memorial", "전몰자 추모식", "전사자의 이름을 하나하나 부르는 추모식을 엽니다. 슬픔은 분노가 되고, 분노는 각오가 됩니다. 전쟁 지지도 +3%, 안정도 +1%.", 35, 120, True,
     ["add_war_support = 0.03", "add_stability = 0.01"]),
    ("civil_defence", "민방위 동원", "방공호를 파고 소방대를 꾸리고, 폭격 맞은 거리를 시민이 직접 치웁니다. 함께 버티는 사람은 쉽게 꺾이지 않습니다. 전쟁 지지도 +8%, 안정도 -2%, 인력 -5천.", 75, 180, True,
     ["add_war_support = 0.08", "add_stability = -0.02", "add_manpower = -5000"]),
    ("parade", "군사 퍼레이드", "평시의 수도에서 군대가 행진합니다. 다음 전쟁을 준비하는 나라라는 것을 국민에게 보여 줍니다. 전쟁 지지도 +4%.", 50, 120, False,
     ["add_war_support = 0.04"]),
]


def main():
    lines = [NOTE + "LR_war_support_category = {"]
    loc = ["l_korean:", ' LR_war_support_category:0 "전쟁 지지 회복"',
           ' LR_war_support_category_desc:0 "폭격과 사상자로 깎인 전쟁 지지도를 되살립니다. 같은 결단은 일정 기간이 지나야 다시 쓸 수 있습니다."']
    for key, name, desc, cost, days, war_only, effects in DECISIONS:
        condition = "has_war = yes" if war_only else "has_war = no"
        lines.append(f"\tLR_dec_ws_{key} = {{\n\t\ticon = generic_propaganda\n\t\tcost = {cost}\n\t\tdays_re_enable = {days}\n"
                     f"\t\tavailable = {{\n\t\t\t{condition}\n\t\t\thas_war_support < 0.9\n\t\t}}\n"
                     "\t\tcomplete_effect = {\n" + "".join(f"\t\t\t{e}\n" for e in effects) + "\t\t}\n"
                     "\t\tai_will_do = {\n\t\t\tfactor = 0\n\t\t\tmodifier = {\n\t\t\t\tadd = 5\n\t\t\t\thas_war_support < 0.5\n\t\t\t}\n\t\t}\n\t}")
        loc += [f' LR_dec_ws_{key}:0 "{name}"', f' LR_dec_ws_{key}_desc:0 "{desc}"']
    lines.append("}")
    (MOD / "common" / "decisions" / "lr_war_support_decisions.txt").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    (MOD / "common" / "decisions" / "categories" / "lr_war_support_categories.txt").write_bytes(
        (NOTE + "LR_war_support_category = {\n\ticon = generic_propaganda\n\tpriority = 50\n}\n").encode("utf-8"))
    (MOD / "localisation" / "korean" / "lr_war_support_l_korean.yml").write_bytes(("﻿" + "\n".join(loc) + "\n").encode("utf-8"))
    print(f"OK: {len(DECISIONS)} war support decisions")


if __name__ == "__main__":
    main()
