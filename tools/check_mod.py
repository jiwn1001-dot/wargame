"""Static checks for the mod. Run before launching the game: python tools/check_mod.py

Checks brace balance, localisation encoding, missing localisation keys, and that
events, characters and sprites referenced by the mod exist in the mod or vanilla.
It cannot prove the game accepts every effect; error.log is still the final check.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "mod"
VANILLA = Path(r"C:\Program Files (x86)\Steam\steamapps\common\Hearts of Iron IV")
errors = []


def strip_comments(text):
    return re.sub(r"#.*", "", text)


scripts = {
    path: strip_comments(path.read_text(encoding="utf-8-sig"))
    for path in ROOT.rglob("*.txt")
}
# Vanilla histories copied with their diplomacy cut (build_diplomacy.py) refer to vanilla characters and DLC art:
# check their braces below, but not their references.
VANILLA_COPIES = {path for path in scripts if "Generated by tools/build_diplomacy.py" in path.read_text(encoding="utf-8-sig", errors="ignore")[:200]}
all_script = "\n".join(text for path, text in scripts.items() if path not in VANILLA_COPIES)

if re.search(r'replace_path\s*=\s*"common/national_focus"', (ROOT / "descriptor.mod").read_text(encoding="utf-8")):
    errors.append("replace_path on common/national_focus crashes the game on day one")

for path, text in scripts.items():
    depth = 0
    for char in text:
        depth += (char == "{") - (char == "}")
        if depth < 0:
            break
    if depth != 0:
        errors.append(f"unbalanced braces: {path.relative_to(ROOT)}")

loc_keys = set()
for path in ROOT.rglob("*.yml"):
    raw = path.read_bytes()
    if not raw.startswith(b"\xef\xbb\xbf"):
        errors.append(f"missing UTF-8 BOM: {path.relative_to(ROOT)}")
    lines = raw.decode("utf-8-sig").splitlines()
    if not lines or lines[0].strip() != "l_korean:":
        errors.append(f"bad header: {path.relative_to(ROOT)}")
    for number, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        match = re.fullmatch(r' ([\w.]+):\d* "(.*)"', line)
        if not match:
            errors.append(f"bad line {path.relative_to(ROOT)}:{number}")
            continue
        loc_keys.add(match.group(1))
        if re.search(r'(?<!\\)"', match.group(2)):
            errors.append(f"unescaped quote {path.relative_to(ROOT)}:{number}")

# Localisation keys the scripts need.
needed = set(re.findall(r"\b(?:title|desc|name) = ([\w.]+\.[\w.]+)", all_script))
for focus in re.findall(r"focus = \{\s*id = (\w+)", all_script):
    needed |= {focus, f"{focus}_desc"}
for character in re.findall(r"^\s*(\w+)=\{\s*name=", all_script, re.M):
    needed.add(character)
needed |= set(re.findall(r"custom_effect_tooltip = ([\w.]+)", all_script))
needed |= set(re.findall(r"tooltip = (LR_\w+)", all_script))
for key in re.findall(r"^\s*(LR_dec_\w+|LR_mission_\w+|LR_FRA_\w+_category) = \{", all_script, re.M):
    needed |= {key, f"{key}_desc"}
for idea in re.findall(r"^\s*(\w+) = \{\s*removal_cost", all_script, re.M):
    needed |= {idea, f"{idea}_desc"}
for key in sorted(needed - loc_keys):
    errors.append(f"missing localisation: {key}")

# Events fired must be defined, and defined events must be in a declared namespace.
defined = set(re.findall(r"^\s*id = (\w+\.\d+)", all_script, re.M))
fired = set(re.findall(r"country_event = \{\s*id = (\w+\.\d+)", all_script))
for event in sorted(fired - defined):
    errors.append(f"undefined event: {event}")
namespaces = set(re.findall(r"add_namespace = (\w+)", all_script))
for event in sorted(defined):
    if event.split(".")[0] not in namespaces:
        errors.append(f"event without namespace: {event}")

# Characters used must be defined.
characters = set(re.findall(r"^\s*(\w+)=\{\s*name=", all_script, re.M))
used = set(re.findall(r"(?:recruit_character|promote_character) = (\w+)", all_script))
for character in sorted(used - characters):
    errors.append(f"undefined character: {character}")

# Sprites must exist in vanilla (or in mod interface files).
sprite_text = "\n".join(
    path.read_text(encoding="utf-8-sig", errors="ignore")
    for base in [VANILLA / "interface", ROOT / "interface"] + sorted(VANILLA.glob("dlc/*/interface"))
    if base.exists()
    for path in base.rglob("*.gfx")
)
sprites = set(re.findall(r'name\s*=\s*"?(GFX_\w+)"?', sprite_text))
for sprite in sorted(set(re.findall(r"\b(GFX_\w+)", all_script)) - sprites):
    errors.append(f"unknown sprite: {sprite}")

# Traits must exist in vanilla (or in the mod).
trait_text = "\n".join(
    path.read_text(encoding="utf-8-sig", errors="ignore")
    for base in (VANILLA / "common" / "unit_leader", VANILLA / "common" / "country_leader")
    for path in base.rglob("*.txt")
)
for block in re.findall(r"(?<![a-z])traits=\{([^}]*)\}", all_script):
    for trait in block.split():
        if not re.search(rf"^\s*{trait}\s*=\s*\{{", trait_text, re.M):
            errors.append(f"unknown trait: {trait}")

# on_startup has no scope, so a scripted effect there must sit inside a country or state block.
NO_SCOPE_BLOCKS = {"on_actions", "on_startup", "effect", "if", "else_if", "else", "hidden_effect"}
actions = strip_comments((ROOT / "common" / "on_actions" / "lr_on_actions.txt").read_text(encoding="utf-8-sig"))
start = actions.index("on_startup")
depth, position, stack = 0, start, []
for match in re.finditer(r"(\w+)\s*=\s*\{|\}|\b(lr_\w+)\s*=\s*yes", actions[start:]):
    if match.group(0) == "}":
        stack.pop()
        if not stack:
            break
    elif match.group(1):
        stack.append(match.group(1))
    elif all(block in NO_SCOPE_BLOCKS or block == "limit" for block in stack):
        errors.append(f"on_startup: {match.group(2)} needs a scope, for example FRA = {{ {match.group(2)} = yes }}")

# A byte-order mark anywhere but the very start of a file breaks the game's parser.
for path in ROOT.rglob("*.txt"):
    if b"\xef\xbb\xbf" in path.read_bytes()[3:]:
        errors.append(f"stray byte-order mark inside {path.relative_to(ROOT)}")
# Effects that do not exist in this game.
for word in ("set_global_variable", "clear_global_variable", "add_to_global_variable"):
    if re.search(rf"{word}", all_script):
        errors.append(f"{word} does not exist: use set_variable = {{ global.name = value }}")

# State history files must not start with a byte-order mark: the game cannot read them then.
for path in (ROOT / "history" / "states").glob("*.txt"):
    if path.read_bytes().startswith(b"\xef\xbb\xbf"):
        errors.append(f"byte-order mark at the start of {path.relative_to(ROOT)}")

if errors:
    print("\n".join(errors))
    sys.exit(1)
print(f"OK: {len(scripts)} scripts, {len(loc_keys)} localisation keys, {len(defined)} events")
