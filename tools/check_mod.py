"""Static checks for the mod. Run before launching the game: python tools/check_mod.py

Checks brace balance, localisation encoding, missing localisation keys, and that
events, characters and sprites referenced by the mod exist in the mod or vanilla.
It cannot prove the game accepts every effect; error.log is still the final check.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "mod"
VANILLA = Path(r"C:\Program Files (x86)\Steam\steamapps\common\Hearts of Iron IV")
errors = []


def strip_comments(text):
    return re.sub(r"#.*", "", text)


scripts = {
    path: strip_comments(path.read_text(encoding="utf-8-sig"))
    for path in ROOT.rglob("*.txt")
}
# Vanilla histories copied with their diplomacy cut (build_diplomacy.py) refer to vanilla characters and DLC art:
# check their braces below, but not their references.
VANILLA_COPIES = {path for path in scripts if re.search(r"Generated by tools/(build_diplomacy|build_oob|build_advisors|kr_layout).py", path.read_text(encoding="utf-8-sig", errors="ignore")[:200])}
all_script = "\n".join(text for path, text in scripts.items() if path not in VANILLA_COPIES)

if re.search(r'replace_path\s*=\s*"common/national_focus"', (ROOT / "descriptor.mod").read_text(encoding="utf-8")):
    errors.append("replace_path on common/national_focus crashes the game on day one")

for path, text in scripts.items():
    depth = 0
    for char in text:
        depth += (char == "{") - (char == "}")
        if depth < 0:
            break
    if depth != 0:
        original = VANILLA / path.relative_to(ROOT)
        if path in VANILLA_COPIES and original.exists():
            plain = strip_comments(original.read_text(encoding="utf-8-sig", errors="ignore"))
            if plain.count("{") - plain.count("}") == text.count("{") - text.count("}"):
                continue  # vanilla's own stray brace, which the game tolerates
        errors.append(f"unbalanced braces: {path.relative_to(ROOT)}")

loc_keys = set()
for path in ROOT.rglob("*.yml"):
    raw = path.read_bytes()
    if not raw.startswith(b"\xef\xbb\xbf"):
        errors.append(f"missing UTF-8 BOM: {path.relative_to(ROOT)}")
    lines = raw.decode("utf-8-sig").splitlines()
    if not lines or lines[0].strip() != "l_korean:":
        errors.append(f"bad header: {path.relative_to(ROOT)}")
    for number, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        match = re.fullmatch(r' ([\w.]+):\d* "(.*)"', line)
        if not match:
            errors.append(f"bad line {path.relative_to(ROOT)}:{number}")
            continue
        loc_keys.add(match.group(1))
        if re.search(r'(?<!\\)"', match.group(2)):
            errors.append(f"unescaped quote {path.relative_to(ROOT)}:{number}")

# Localisation keys the scripts need.
needed = set(re.findall(r"\b(?:title|desc|name) = ([\w.]+\.[\w.]+)", all_script))
for focus in re.findall(r"focus = \{\s*id = (\w+)", all_script):
    needed |= {focus, f"{focus}_desc"}
for character in re.findall(r"^\s*(\w+)=\{\s*name=", all_script, re.M):
    needed.add(character)
needed |= set(re.findall(r"custom_effect_tooltip = ([\w.]+)", all_script))
needed |= set(re.findall(r"tooltip = (LR_\w+)", all_script))
for key in re.findall(r"^\s*(LR_dec_\w+|LR_mission_\w+|LR_FRA_\w+_category) = \{", all_script, re.M):
    needed |= {key, f"{key}_desc"}
for idea in re.findall(r"^\s*(\w+) = \{\s*removal_cost", all_script, re.M):
    needed |= {idea, f"{idea}_desc"}
for key in sorted(needed - loc_keys):
    errors.append(f"missing localisation: {key}")

# Events fired must be defined, and defined events must be in a declared namespace.
defined = set(re.findall(r"^\s*id = (\w+\.\d+)", all_script, re.M))
fired = set(re.findall(r"country_event = \{\s*id = (\w+\.\d+)", all_script))
for event in sorted(fired - defined):
    errors.append(f"undefined event: {event}")
namespaces = set(re.findall(r"add_namespace = (\w+)", all_script))
for event in sorted(defined):
    if event.split(".")[0] not in namespaces:
        errors.append(f"event without namespace: {event}")

# A state history's victory_points block takes one province and one value; more is an error in game.
for path in (ROOT / "history" / "states").glob("*.txt"):
    text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig", errors="ignore"))
    for block in re.findall(r"victory_points\s*=\s*\{([^}]*)\}", text):
        if "province" not in block and len(block.split()) != 2:
            errors.append(f"victory_points needs one pair per block: {path.name}")

# Characters used must be defined.
characters = set(re.findall(r"^\s*(\w+)=\{\s*name=", all_script, re.M))
used = set(re.findall(r"(?:recruit_character|promote_character) = (\w+)", all_script))
for character in sorted(used - characters):
    errors.append(f"undefined character: {character}")

# Sprites must exist in vanilla (or in mod interface files).
sprite_text = "\n".join(
    path.read_text(encoding="utf-8-sig", errors="ignore")
    for base in [VANILLA / "interface", ROOT / "interface"] + sorted(VANILLA.glob("dlc/*/interface"))
    if base.exists()
    for path in base.rglob("*.gfx")
)
sprites = set(re.findall(r'name\s*=\s*"?(GFX_\w+)"?', sprite_text))
for sprite in sorted(set(re.findall(r"\b(GFX_\w+)", all_script)) - sprites):
    errors.append(f"unknown sprite: {sprite}")

# Traits must exist in vanilla (or in the mod).
trait_text = "\n".join(
    path.read_text(encoding="utf-8-sig", errors="ignore")
    for base in (VANILLA / "common" / "unit_leader", VANILLA / "common" / "country_leader", ROOT / "common" / "country_leader")
    for path in base.rglob("*.txt")
)
for block in re.findall(r"(?<![a-z])traits=\{([^}]*)\}", all_script):
    for trait in block.split():
        if not re.search(rf"^\s*{trait}\s*=\s*\{{", trait_text, re.M):
            errors.append(f"unknown trait: {trait}")

# on_startup has no scope, so a scripted effect there must sit inside a country or state block.
NO_SCOPE_BLOCKS = {"on_actions", "on_startup", "effect", "if", "else_if", "else", "hidden_effect"}
actions = strip_comments((ROOT / "common" / "on_actions" / "lr_on_actions.txt").read_text(encoding="utf-8-sig"))
start = actions.index("on_startup")
depth, position, stack = 0, start, []
for match in re.finditer(r"(\w+)\s*=\s*\{|\}|\b(lr_\w+)\s*=\s*yes", actions[start:]):
    if match.group(0) == "}":
        stack.pop()
        if not stack:
            break
    elif match.group(1):
        stack.append(match.group(1))
    elif all(block in NO_SCOPE_BLOCKS or block == "limit" for block in stack):
        errors.append(f"on_startup: {match.group(2)} needs a scope, for example FRA = {{ {match.group(2)} = yes }}")

# A byte-order mark anywhere but the very start of a file breaks the game's parser.
for path in ROOT.rglob("*.txt"):
    if b"\xef\xbb\xbf" in path.read_bytes()[3:]:
        errors.append(f"stray byte-order mark inside {path.relative_to(ROOT)}")
# Effects that do not exist in this game.
for word in ("set_global_variable", "clear_global_variable", "add_to_global_variable"):
    if re.search(rf"{word}", all_script):
        errors.append(f"{word} does not exist: use set_variable = {{ global.name = value }}")

# The game reads a byte-order mark at the start of on_actions and character files as part of the first token,
# and then drops the whole file (error.log: "Unexpected token: <BOM>on_actions"). That silently skipped the startup.
for folder in ("on_actions", "characters"):
    for path in (ROOT / "common" / folder).glob("lr_*.txt"):
        if path.read_bytes().startswith(b"\xef\xbb\xbf"):
            errors.append(f"byte-order mark at the start of {path.relative_to(ROOT)}: the game drops the whole file")

# State history files must not start with a byte-order mark: the game cannot read them then.
for path in (ROOT / "history" / "states").glob("*.txt"):
    if path.read_bytes().startswith(b"\xef\xbb\xbf"):
        errors.append(f"byte-order mark at the start of {path.relative_to(ROOT)}")


def map_checks():
    """What the game checks on loading the map: every building position lies in a province of its own state (a coastal
    province whose port is ignored crashes the game), and every state's provinces lie in one strategic region."""
    import numpy as np
    from PIL import Image
    histories = {p.name: p for p in (VANILLA / "history" / "states").glob("*.txt")}
    histories.update({p.name: p for p in (ROOT / "history" / "states").glob("*.txt")})
    state_of = {}
    provinces_of = {}
    for path in histories.values():
        text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig", errors="ignore"))
        sid = int(re.search(r"\bid\s*=\s*(\d+)", text).group(1))
        provinces_of[sid] = [int(p) for p in re.search(r"provinces\s*=\s*\{([^}]*)\}", text).group(1).split()]
        for p in provinces_of[sid]:
            state_of[p] = sid
    colours = {}
    for line in ((ROOT / "map" / "definition.csv") if (ROOT / "map" / "definition.csv").exists() else (VANILLA / "map" / "definition.csv")).read_text(encoding="utf-8-sig", errors="ignore").splitlines():
        parts = line.split(";")
        if len(parts) > 3 and parts[0].isdigit():
            colours[(int(parts[1]) << 16) | (int(parts[2]) << 8) | int(parts[3])] = int(parts[0])
    pixels = np.asarray(Image.open((ROOT / "map" / "provinces.bmp") if (ROOT / "map" / "provinces.bmp").exists() else (VANILLA / "map" / "provinces.bmp")).convert("RGB"), dtype=np.uint32)
    keys = (pixels[..., 0] << 16) | (pixels[..., 1] << 8) | pixels[..., 2]
    lookup = np.zeros(int(keys.max()) + 1, dtype=np.int32)
    for key, pid in colours.items():
        lookup[key] = pid
    prov_map = lookup[keys]
    height, width = prov_map.shape
    buildings = (ROOT / "map" / "buildings.txt")
    if buildings.exists():
        wrong = []
        for number, line in enumerate(buildings.read_text(encoding="utf-8-sig").splitlines(), 1):
            parts = line.split(";")
            if len(parts) != 7:
                errors.append(f"map/buildings.txt line {number}: {len(parts)} fields, the game expects 7")
                continue
            sid, kind, x, z = int(parts[0]), parts[1], float(parts[2]), float(parts[4])
            row, col = height - 1 - int(z), int(x)
            if not (0 <= row < height and 0 <= col < width):
                continue
            here = state_of.get(int(prov_map[row, col]))
            if here is not None and here != sid and (kind == "naval_base_spawn" or sid in provinces_of and here in provinces_of):
                wrong.append((number, kind, sid, here))
        for number, kind, sid, here in wrong:
            if kind == "naval_base_spawn":
                errors.append(f"map/buildings.txt line {number}: the port of state {here} is filed under state {sid}; "
                              "the game ignores it and crashes on the coastal province without a port")
        # Position kinds every vanilla state has (air base, rocket site, coastal gun...) must exist in every state too:
        # an air wing deploying to a state without an air base position crashes the game on the first day.
        def kinds(path):
            out = {}
            for line in path.read_text(encoding="utf-8-sig").splitlines():
                parts = line.split(";")
                if len(parts) == 7 and parts[0].isdigit():
                    out.setdefault(int(parts[0]), set()).add(parts[1])
            return out
        vanilla_kinds = kinds(VANILLA / "map" / "buildings.txt")
        universal = set.intersection(*vanilla_kinds.values()) if vanilla_kinds else set()
        mod_kinds = kinds(buildings)
        for sid in sorted(provinces_of):
            missing = universal - mod_kinds.get(sid, set())
            if missing:
                errors.append(f"state {sid}: no building position for {sorted(missing)} in map/buildings.txt")
        others = [w for w in wrong if w[1] != "naval_base_spawn"]
        if others:
            print(f"note: {len(others)} building positions lie in a neighbouring state and will be ignored, "
                  f"e.g. line {others[0][0]} ({others[0][1]})")
    region_of = {}
    region_files = {p.name: p for p in (VANILLA / "map" / "strategicregions").glob("*.txt")}
    region_files.update({p.name: p for p in (ROOT / "map" / "strategicregions").glob("*.txt")})  # the mod's over vanilla's
    for path in region_files.values():
        text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig", errors="ignore"))
        rid = re.search(r"\bid\s*=\s*(\d+)", text)
        found = re.search(r"provinces\s*=\s*\{([^}]*)\}", text)
        if rid and found:
            for p in found.group(1).split():
                region_of[int(p)] = int(rid.group(1))
    for sid, provs in provinces_of.items():
        regions = {region_of.get(p) for p in provs if p in region_of}
        if len(regions) > 1 and any(path.parent.parent.parent == ROOT for path in histories.values()
                                    if path.name.split("-")[0].strip() == str(sid)):
            errors.append(f"state {sid}: provinces in {len(regions)} strategic regions ({sorted(regions)})")


map_checks()

if errors:
    print("\n".join(errors))
    sys.exit(1)
print(f"OK: {len(scripts)} scripts, {len(loc_keys)} localisation keys, {len(defined)} events")
