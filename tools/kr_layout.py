"""Lay the world's states out as Kaiserreich draws them: python tools/kr_layout.py

    python tools/kr_layout.py --compute   once, with Kaiserreich installed: which Kaiserreich state lies under each
                                          vanilla province (tools/kr_layout.json); the build then runs without it

The steps before this one build the mod on vanilla's states (with the pieces split_states.py cuts). This step, run
after every other writer, regroups all the provinces into Kaiserreich's states and renumbers them:

  - every land province goes to the Kaiserreich state under it; a state is also split where two owners meet (the
    political map stays as the earlier steps made it) and where vanilla's strategic regions meet (the game requires
    a state to lie in one region); a single stray province whose Kaiserreich state lies elsewhere joins a neighbour;
  - each vanilla state id goes to the new state that overlaps it most, so vanilla's own scripts still point at about
    the same place; the remaining new states take the ids after;
  - factories, resources and manpower are shared out by provinces; victory points, ports and forts stay with their
    provinces; air bases and the like stay with the state holding most of the old one;
  - every state number in the mod's scripts and texts is translated: where an old state became several, effects and
    triggers name all of them (transfer_state, state = in lists, state scopes) and single places (capitals, air wings)
    take the largest.

Files the build does not rewrite (hand-written events, the air orders of battle) are kept in their original
numbering in tools/kr_layout_cache and translated again from there on every build. A file edited by hand after it was
translated is left alone with a warning.
"""
