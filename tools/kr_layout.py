# ---------------------------------------------------------------------------------------------- script parsing
def tokens(text):
    for m in re.finditer(r'#[^\n]*|"[^"]*"|[{}=]|[^\s{}="#]+', text):  # comments first: "5 # Brunei"
        tok = m.group(0)
        if not tok.startswith("#"):
            yield tok


def parse(text):
    """Clausewitz text -> list of (key, value); a value is a string or such a list. A bare list ({ 1 2 3 }) is a list
    of (word, None)."""
    toks = list(tokens(text))
    pos = 0

    def block():
        nonlocal pos
        out = []
        while pos < len(toks):
            tok = toks[pos]
            if tok == "}":
                pos += 1
                return out
            if pos + 1 < len(toks) and toks[pos + 1] == "=":
                pos += 2
                if toks[pos] == "{":
                    pos += 1
                    out.append((tok, block()))
                else:
                    out.append((tok, toks[pos]))
                    pos += 1
            elif tok == "{":
                pos += 1
                out.append((None, block()))
            else:
                out.append((tok, None))
                pos += 1
        return out

    return block()


def dump(items, depth):
    pad = "\t" * depth
    lines = []
    for key, value in items:
        if isinstance(value, list):
            if all(v is None for _, v in value) and value:
                lines.append(f"{pad}{key} = {{ {' '.join(k for k, _ in value)} }}")
            else:
                lines.append(f"{pad}{key} = {{")
                lines.extend(dump(value, depth + 1))
                lines.append(f"{pad}}}")
        elif value is None:
            lines.append(f"{pad}{key}")
        else:
            lines.append(f"{pad}{key} = {value}")
    return lines


def get(items, key, default=None):
    return next((v for k, v in items if k == key), default)


def is_date(key):
    return bool(key and re.fullmatch(r"\d+\.\d+\.\d+(\.\d+)?", key))


