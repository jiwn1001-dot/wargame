def translate(text, remap, history_units=False, max_old=0):
    """The text with every state number in the new numbering."""
    out = []
    stack = []          # keys of the open blocks
    seen_blocks = set()
    i = 0
    # A key is a whole word: "1936.1.1 = {" is a date, not state 1.
    pattern = re.compile(r'"[^"]*"|#[^\n]*|[{}]|(?<![\w.:@$])(\w+)(\s*=\s*)(\{|\d+(?![\d.]))?')
    last = 0
    while True:
        m = pattern.search(text, i)
        if not m:
            break
        tok = m.group(0)
        if tok.startswith('"') or tok.startswith("#"):
            i = m.end()
            continue
        if tok == "{":
            stack.append(None)
            i = m.end()
            continue
        if tok == "}":
            if stack:
                stack.pop()
            i = m.end()
            continue
        key, eq, value = m.group(1), m.group(2), m.group(3)
        if value is None:
            i = m.end()
            continue
        if value == "{":
            if key.isdigit() and int(key) <= max_old and int(key) in remap and "random_list" not in stack \
                    and not any(s and s.startswith("random") and s.endswith("list") for s in stack):
                # A state scope: one block per new state (one only for an air wing's base).
                depth, end = 1, m.end()
                while depth and end < len(text):
                    depth += {"{": 1, "}": -1}.get(text[end], 0)
                    end += 1
                body = text[m.end():end - 1]
                once = history_units or ONCE.search(body)  # an air wing's base, or a building: the largest piece only
                targets = remap[int(key)][:1] if once else remap[int(key)]
                body = translate(body, remap, history_units, max_old)
                line_start = text.rfind("\n", 0, m.start()) + 1
                indent = re.match(r"[ \t]*", text[line_start:m.start()]).group(0)
                # Two old states merged into one would get the same block twice (a resistance started twice).
                pieces = [f"{t}{eq}{{{body}}}" for t in targets if (t, body.strip()) not in seen_blocks]
                seen_blocks.update((t, body.strip()) for t in targets)
                out.append(text[last:m.start()] + ("\n" + indent).join(pieces))
                last = i = end
                continue
            if key in ("states", "targets"):  # a list of states (start_civil_war, a decision's targets): every piece
                # (A list of country tags under the same key is left alone: it holds no numbers.)
                end = text.index("}", m.end())
                words = text[m.end():end].split()
                if all(w.isdigit() for w in words):
                    listed = []
                    for w in words:
                        for t in (remap[int(w)] if int(w) in remap and int(w) <= max_old else [int(w)]):
                            if t not in listed:
                                listed.append(t)
                    out.append(text[last:m.end()] + " " + " ".join(map(str, listed)) + " ")
                    last = i = end
                    continue
            stack.append(key)
            i = m.end()
            continue
        number = int(value)
        new = None
        if number in remap and number <= max_old:
            targets = remap[number]
            if key in EVERY:
                new = " ".join(f"{key} = {t}" for t in targets)
            elif key in ALL_OF:
                new = f"{key} = {targets[0]}" if len(targets) == 1 else "AND = { " + " ".join(f"{key} = {t}" for t in targets) + " }"
            elif key in ONE:
                new = f"{key}{eq}{targets[0]}"
            elif key == "state":
                parent = next((s for s in reversed(stack) if s is not None), None)
                is_trigger = parent in TRIGGER_BLOCKS or (parent or "").startswith(("any_", "all_"))
                if is_trigger and len(targets) > 1:
                    new = "OR = { " + " ".join(f"state = {t}" for t in targets) + " }"
                else:
                    new = f"state{eq}{targets[0]}"
        if new is not None:
            out.append(text[last:m.start()] + new)
            last = m.end()
        i = m.end()
    out.append(text[last:])
    return "".join(out)


def translate_loc(text, remap):
    return re.sub(r"\$STATE_(\d+)\$", lambda m: f"$STATE_{remap[int(m.group(1))][0]}$" if int(m.group(1)) in remap else m.group(0), text)


