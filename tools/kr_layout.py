def write_regions(region):
    """The strategic regions whose land borders layout() moved, written over vanilla's files of the same names."""
    files = {p.name: p for p in (VANILLA / "map" / "strategicregions").glob("*.txt")}
    files.update({p.name: p for p in (MOD / "map" / "strategicregions").glob("*.txt")})
    inside = defaultdict(list)
    for p, rid in region.items():
        inside[rid].append(p)
    out = MOD / "map" / "strategicregions"
    out.mkdir(parents=True, exist_ok=True)
    changed = 0
    for name, path in files.items():
        text = path.read_text(encoding="utf-8-sig", errors="ignore")
        top = get(parse(text), "strategic_region", [])
        rid = int(get(top, "id"))
        old = [int(p) for p, _ in get(top, "provinces", [])]
        now = set(inside[rid])
        if not old and not now:
            continue  # vanilla's own empty region (15, "Asia")
        if not now:
            raise SystemExit(f"strategic region {rid} ({name}) would be left without provinces")
        if set(old) == now:
            continue
        kept = [p for p in old if p in now]
        provs = kept + sorted(now - set(kept))
        plain = re.sub(r"#[^\n]*", "", text)  # a comment inside the list would hide a brace from the pattern
        new = re.sub(r"(provinces\s*=\s*\{)[^}]*\}", lambda m: m.group(1) + "\n\t\t" + " ".join(map(str, provs)) + "\n\t}", plain, count=1)
        (out / name).write_text(NOTE + new, encoding="utf-8")
        changed += 1
    return changed


def country_tags():
    """The country tags the game knows: vanilla's and the mod's."""
    tags = set()
    for folder in (VANILLA / "common" / "country_tags", MOD / "common" / "country_tags"):
        for path in folder.glob("*.txt"):
            tags.update(re.findall(r"^\s*([A-Z][A-Z0-9]{2})\s*=", re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig", errors="ignore")), re.M))
    return tags


