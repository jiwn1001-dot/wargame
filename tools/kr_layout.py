def write_buildings(states, new, finals, ids, main):
    import numpy as np
    prov_map = province_pixels()
    height = prov_map.shape[0]
    final_of = {p: f for f, ps in enumerate(finals) for p in ps}
    old_provs = {sid: set(s["provinces"]) for sid, s in states.items()}

    def province_at(x, z, allowed):
        row, col = height - 1 - int(z), int(x)
        here = int(prov_map[row, col]) if 0 <= row < height and 0 <= col < prov_map.shape[1] else 0
        if here in allowed:
            return here
        best, best_d = None, None
        for dr in range(-4, 5):
            for dc in range(-4, 5):
                r, c = row + dr, col + dc
                if 0 <= r < height and 0 <= c < prov_map.shape[1] and int(prov_map[r, c]) in allowed:
                    d = dr * dr + dc * dc
                    if best_d is None or d < best_d:
                        best, best_d = int(prov_map[r, c]), d
        return best

    kinds = province_kinds()
    # Each province's pixels, found once (a whole-map scan per state is slow).
    flat = prov_map.ravel()
    order = np.argsort(flat, kind="stable")
    starts = np.searchsorted(flat[order], np.arange(int(flat.max()) + 2))
    width = prov_map.shape[1]

    def pixels(provs):
        idx = np.sort(np.concatenate([order[starts[p]:starts[p + 1]] for p in provs]))
        return idx // width, idx % width

    def land_point(provs):
        """A point on the state's land, near its middle (a state can hold a lake, and the game drops a building
        position that lies on water)."""
        land = [p for p in provs if kinds.get(p) == "land"] or list(provs)
        ys, xs = pixels(land)
        i = int(np.argmin((xs - xs.mean()) ** 2 + (ys - ys.mean()) ** 2))
        return float(xs[i]) + 0.5, float(height - 1 - ys[i]) + 0.5

    source = MOD / "map" / "buildings.txt"
    if not source.exists():
        source = VANILLA / "map" / "buildings.txt"
    rows, kinds_of_old = [], defaultdict(set)
    for line in source.read_text(encoding="utf-8-sig", errors="ignore").splitlines():
        parts = line.split(";")
        if len(parts) < 7 or not parts[0].isdigit():
            continue
        old = int(parts[0])
        kinds_of_old[old].add(parts[1])
        # The game files a position under the state of the province it stands on, so that is the state it gets;
        # one standing on water (a floating harbour) stays with the nearest province of its old state.
        row, col = height - 1 - int(float(parts[4])), int(float(parts[2]))
        p = int(prov_map[row, col]) if 0 <= row < height and 0 <= col < prov_map.shape[1] else 0
        if parts[1] not in ("floating_harbor", "naval_base_spawn") and kinds.get(p) != "land":
            continue  # on a lake or the sea: the game drops it; the state gets one on land below if it needs it
        if p not in final_of:
            p = province_at(float(parts[2]), float(parts[4]), old_provs.get(old, set()))
        f = final_of.get(p, main.get(old))
        if f is None:
            continue
        parts[0] = str(ids[f])
        rows.append(parts)
    have = defaultdict(set)
    heights = defaultdict(list)
    for parts in rows:
        have[int(parts[0])].add(parts[1])
        heights[int(parts[0])].append(float(parts[3]))
    universal = set.intersection(*[k for k in kinds_of_old.values() if k]) if kinds_of_old else set()
    for f, ps in enumerate(finals):
        sid = ids[f]
        wanted = set(universal)
        for old in {states_id for states_id, s in states.items() if set(ps) & old_provs[states_id]}:
            wanted |= kinds_of_old.get(old, set())
        missing = sorted(wanted - have[sid] - COASTAL_KINDS)
        if missing:
            x, z = land_point(ps)
            y = sum(heights[sid]) / len(heights[sid]) if heights[sid] else 10.0
            rows += [[str(sid), kind, f"{x:.2f}", f"{y:.2f}", f"{z:.2f}", "0.00", "0"] for kind in missing]
    # Every coastal province needs a port position of its own in its state, built or not: the game crashes on a
    # coastal province without one ("setup as coastal but has no port building in the nudger"). The provinces
    # kr_provinces.py cut have none, and a cut can leave the parent's on the other side.
    ports = set()
    port_heights = []
    for parts in rows:
        if parts[1] == "naval_base_spawn":
            row, col = height - 1 - int(float(parts[4])), int(float(parts[2]))
            here = int(prov_map[row, col])
            if here in final_of and ids[final_of[here]] == int(parts[0]):
                ports.add(here)
                port_heights.append(float(parts[3]))
    port_y = sum(port_heights) / len(port_heights) if port_heights else 9.6
    for p in sorted(coastal_provinces() - ports):
        if p not in final_of or kinds.get(p) != "land":
            continue
        ys, xs = pixels([p])
        found = None
        for y, x in zip(ys.tolist(), xs.tolist()):
            for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)):
                r, c = y + dy, x + dx
                if 0 <= r < height and 0 <= c < prov_map.shape[1] and kinds.get(int(prov_map[r, c])) == "sea":
                    found = (x, y, int(prov_map[r, c]))
                    break
            if found:
                break
        if not found:
            raise SystemExit(f"province {p} is marked coastal but touches no sea")
        x, y, sea = found
        rows.append([str(ids[final_of[p]]), "naval_base_spawn", f"{x + 0.5:.2f}", f"{port_y:.2f}",
                     f"{height - 1 - y + 0.5:.2f}", "0.00", str(sea)])
    (MOD / "map" / "buildings.txt").write_text("\n".join(";".join(r) for r in rows), encoding="utf-8")
    return len(rows)


