def province_pixels():
    import numpy as np
    from PIL import Image
    colours = {}
    for line in map_file("definition.csv").read_text(encoding="utf-8-sig", errors="ignore").splitlines():
        parts = line.split(";")
        if len(parts) > 3 and parts[0].isdigit():
            colours[(int(parts[1]) << 16) | (int(parts[2]) << 8) | int(parts[3])] = int(parts[0])
    pixels = np.asarray(Image.open(map_file("provinces.bmp")).convert("RGB"), dtype=np.uint32)
    keys = (pixels[..., 0] << 16) | (pixels[..., 1] << 8) | pixels[..., 2]
    lookup = np.zeros(keys.max() + 1, dtype=np.int32)
    for key, pid in colours.items():
        lookup[key] = pid
    return lookup[keys]


def province_centres():
    import numpy as np
    prov = province_pixels()
    ys, xs = np.indices(prov.shape)
    flat = prov.ravel()
    n = np.bincount(flat)
    sx = np.bincount(flat, weights=xs.ravel())
    sy = np.bincount(flat, weights=ys.ravel())
    return {int(p): (sx[p] / n[p], sy[p] / n[p]) for p in np.nonzero(n)[0] if p}


def compute():
    """Which Kaiserreich state lies under each vanilla province (by pixels), and which provinces touch."""
    import numpy as np
    sys.path.insert(0, str(TOOLS))
    import kr_regions as k
    v = province_pixels().astype(np.int64)  # the mod's map, with the provinces kr_provinces.py cut
    kp = k.province_map(k.KR).astype(np.int64)
    pair, counts = np.unique(v.ravel() * 100000 + kp.ravel(), return_counts=True)
    best = {}
    for code, n in zip(pair.tolist(), counts.tolist()):
        a, b = divmod(code, 100000)
        if a and b and n > best.get(a, (0, 0))[1]:
            best[a] = (b, n)
    k_state_of = {p: s for s, ps in k.provinces_of_states(k.KR).items() for p in ps}
    under = {a: k_state_of[b] for a, (b, _) in best.items() if b in k_state_of}
    touches = set()
    for x, y in ((v[1:, :], v[:-1, :]), (v[:, 1:], v[:, :-1])):
        m = x != y
        codes = np.unique(np.minimum(x[m], y[m]) * 100000 + np.maximum(x[m], y[m]))
        touches.update(divmod(int(c), 100000) for c in codes)
    kr_owner, kr_claims = {}, {}
    for path in (k.KR / "history" / "states").glob("*.txt"):
        text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig", errors="ignore"))
        sid, owner = re.search(r"\bid\s*=\s*(\d+)", text), re.search(r"\bowner\s*=\s*(\w+)", text)
        if sid and owner:
            kr_owner[int(sid.group(1))] = owner.group(1)
            # Who holds a core or claim there in Kaiserreich: this world's historical claims (build_states adds them).
            kr_claims[int(sid.group(1))] = sorted(set(re.findall(r"\b(?:add_core_of|add_claim_by)\s*=\s*(\w+)", text)))
    DATA.write_text(json.dumps({"kr_state": {str(a): s for a, s in sorted(under.items())},
                                "kr_owner": {str(s): o for s, o in sorted(kr_owner.items())},
                                "kr_claims": {str(s): c for s, c in sorted(kr_claims.items()) if c},
                                "touch": sorted([a, b] for a, b in touches if a and b)}), encoding="utf-8")
    print(f"OK: {len(under)} provinces under Kaiserreich states, {len(touches)} borders")


def regions():
    out = {}
    files = {p.name: p for p in (VANILLA / "map" / "strategicregions").glob("*.txt")}
    files.update({p.name: p for p in (MOD / "map" / "strategicregions").glob("*.txt")})
    for path in files.values():
        top = get(parse(path.read_text(encoding="utf-8-sig", errors="ignore")), "strategic_region", [])
        rid = int(get(top, "id"))
        for p, _ in get(top, "provinces", []):
            out[int(p)] = rid
