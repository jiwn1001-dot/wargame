def read_state(text):
    top = parse(text)
    state = get(top, "state", [])
    hist = [(k, v) for k, v in get(state, "history", []) if not is_date(k)]  # the 1936 start only
    out = {
        "id": int(get(state, "id")),
        "manpower": int(float(get(state, "manpower", "0"))),
        "category": get(state, "state_category", "rural"),
        "impassable": get(state, "impassable") == "yes",
        "supplies": get(state, "local_supplies", "0.0"),
        "provinces": [int(k) for k, _ in get(state, "provinces", [])],
        "resources": {k: float(v) for k, v in get(state, "resources", []) if v is not None and not isinstance(v, list)},
        "owner": get(hist, "owner"),
        "cores": [v for k, v in hist if k == "add_core_of"],
        "claims": [v for k, v in hist if k == "add_claim_by"],
        "vps": [],
        "levels": {},        # state buildings: name -> level
        "province_blocks": {},
        "extras": [],
        # Other top-level lines (buildings_max_level_factor...), kept with the state holding most of this one.
        "top": [(k, v) for k, v in state if k not in ("id", "name", "manpower", "state_category", "impassable",
                                                       "local_supplies", "provinces", "resources", "history")],
    }
    for key, value in hist:
        if key == "victory_points":
            words = [k for k, _ in value] if isinstance(value, list) else []
            if words and words[0] == "province":
                pairs = dict(value)
                out["vps"].append((int(pairs["province"]), pairs["value"]))
            else:
                out["vps"] += [(int(a), b) for a, b in zip(words[::2], words[1::2])]
        elif key == "buildings":
            for bkey, bvalue in value:
                if bkey and bkey.isdigit() and isinstance(bvalue, list):
                    out["province_blocks"][int(bkey)] = bvalue
                elif bvalue is not None and not isinstance(bvalue, list):
                    out["levels"][bkey] = float(bvalue)
        elif key in ("owner", "controller", "add_core_of", "add_claim_by", "set_demilitarized_zone"):
            continue
        elif key in ("IF", "if") and isinstance(value, list) and get(value, "transfer_state_to"):
            # Vanilla hands a state to another country for a DLC's owners (the Belgian Congo, Götterdämmerung). The
            # state's owner is that country from the start, so every state the province goes into agrees; carried
            # along as an effect it reached only some of them and split the Congo.
            out["handed_from"] = out["owner"]
            out["owner"] = get(value, "transfer_state_to")
            rest = [(k, v) for k, v in value if k not in ("limit", "transfer_state_to")]
            out["extras"] += rest
        else:
            out["extras"].append((key, value))
    return out


def load_states():
    """The states as the earlier steps left them: the mod's files over vanilla's, by file name."""
    files = {p.name: p for p in (VANILLA / "history" / "states").glob("*.txt")}
    files.update({p.name: p for p in (MOD / "history" / "states").glob("*.txt")})
    states, file_of = {}, {}
    for name, path in files.items():
        text = path.read_text(encoding="utf-8-sig", errors="ignore")
        if NOTE.strip() in text[:200]:
            raise SystemExit("The states are already laid out by kr_layout.py: run build_world.py (or the whole build) first.")
        if not re.search(r"\bid\s*=\s*\d+", text):
            continue
        s = read_state(text)
        states[s["id"]] = s
        file_of[s["id"]] = name
    # Pieces split_states.py cut from such a state follow it (their files were written without the vanilla hand-over).
    sys.path.insert(0, str(TOOLS))
    import split_states
    for orig, parts in split_states.pieces().items():
        s = states.get(orig)
        if s and s.get("handed_from"):
            for new, _ in parts:
                if new in states and states[new]["owner"] == s["handed_from"]:
                    states[new]["owner"] = s["owner"]
    # Provinces kr_provinces.py cut from vanilla's start in their parent's state.
    import kr_provinces
    children = defaultdict(list)
    for new, parent in kr_provinces.new_provinces().items():
        children[parent].append(new)
    for s in states.values():
        s["provinces"] += [c for p in list(s["provinces"]) for c in children.get(p, [])]
    return states, file_of


