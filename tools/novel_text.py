def patch_last(path):
    """Write each scene's "last" text over its event's .d line in the given loc file."""
    import re
    raw = path.read_bytes().decode("utf-8-sig")
    for event, scene in NOVEL.items():
        if "last" not in scene:
            continue
        line = f' {event}.d:0 "{scene["last"]}"'
        raw, count = re.subn(rf'^ {re.escape(event)}\.d:0 ".*"(?=\r?$)', lambda _m: line, raw, flags=re.M)
        assert count <= 1, event
    path.write_bytes(("﻿" + raw).encode("utf-8"))
