def josa(word, pair):
    """Attach the right particle: pair is ("과", "와"), ("이", "가") and so on, after a final consonant or a vowel."""
    last = word.rstrip()[-1]
    final = "가" <= last <= "힣" and (ord(last) - 0xAC00) % 28
    return word + (pair[0] if final else pair[1])


