def _focus_ids():
    path = Path(__file__).resolve().parent.parent / "mod" / "common" / "national_focus" / "france.txt"
    return set(re.findall(r"id = (LR_[A-Z]{3}_\w+)", path.read_text(encoding="utf-8"))) if path.exists() else set()


def build():
    ids = _focus_ids()
    out = {}
    for fid in sorted(ids):
        prefix, key = fid[3:6], fid[7:]
        text = ROUTES.get(prefix, {}).get(key) or PLAN_VOICES.get(VOICE_OF.get(prefix), {}).get(key) or SHARED.get(key)
        if text is None and key == "found_bloc" and prefix in BLOC_OF:
            text = BLOC[BLOC_OF[prefix]]
        if text:
            out[f"{fid}_desc"] = text
    return out


